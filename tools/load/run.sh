#!/bin/zsh
# Замер нагрузки на копии магазина — только локально, боевую базу не трогает.
#
#   tools/load/run.sh [итог.json]
#
# Заводит временную локальную базу partut_load_<номер> (Postgres на
# 127.0.0.1:5433, как у тестов на Postgres), поднимает стенд
# tools/load/stand.py на свободном порту, прогоняет tools/load/run.py,
# останавливает стенд и удаляет базу. Минуты полторы.
#
# Чужого не трогает (приёмка LOAD-01): раньше скрипт перед запуском убивал
# всё, что слушало порт 8793, — посторонний сервис тоже. Теперь порт берётся
# свободный, а заданный вручную (LOAD_PORT) и занятый — отказ, а не «освободить»;
# останавливается только свой стенд, удаляется только своя база.
#
# «До и после» — тот же замер на старом коде из рабочей копии git:
#
#   git worktree add /tmp/partut-old <коммит>
#   LOAD_ROOT=/tmp/partut-old tools/load/run.sh до.json
#   tools/load/run.sh после.json
#
# Между прогонами — минута паузы: закрытые соединения держат порты ещё
# полминуты, и следующий прогон иначе споткнётся о чужой хвост.
#
# Ещё: ONLY=race,mix — только эти разделы; KEEPALIVE=0 — новое соединение на
# каждый запрос; LOAD_PORT — порт стенда (по умолчанию любой свободный);
# PG_BIN — где лежат createdb/dropdb; LOAD_DB_PORT, LOAD_DB_USER.
set -e
ЗДЕСЬ=${0:A:h}
КОРЕНЬ=${ЗДЕСЬ:h:h}
ИТОГ=${1:-load_result.json}
ПИТОН=$КОРЕНЬ/venv/bin/python
export PATH="${PG_BIN:-/opt/homebrew/opt/postgresql@16/bin}:$PATH"
ПОРТ_БАЗЫ=${LOAD_DB_PORT:-5433}
ХОЗЯИН=${LOAD_DB_USER:-partut}
# Своя база на каждый замер: постоянную не пересоздаём и чужую не заденем.
export LOAD_DB_NAME="partut_load_$$_$RANDOM"

слушает() { lsof -nP -iTCP:$1 -sTCP:LISTEN -t 2>/dev/null; }
if [[ -n "$LOAD_PORT" ]]; then
  ПОРТ=$LOAD_PORT
  if [[ -n "$(слушает $ПОРТ)" ]]; then
    echo "Порт $ПОРТ уже занят (процесс $(слушает $ПОРТ | tr '\n' ' ')) — замер не запущен."
    echo "Освободите порт сами или не задавайте LOAD_PORT: тогда возьмётся свободный."
    exit 1
  fi
else
  ПОРТ=$($ПИТОН -c 'import socket; s = socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1])')
fi

СТЕНД=""
БАЗА_ЕСТЬ=""
убрать() {
  # Без set -e: остановленный стенд отвечает wait кодом 143, и уборка
  # обрывалась на нём, не дойдя до базы. Здесь каждый шаг — при любом исходе.
  setopt local_options no_err_exit
  if [[ -n "$СТЕНД" ]]; then kill $СТЕНД 2>/dev/null; wait $СТЕНД 2>/dev/null; fi
  # --force: соединения только что остановленного стенда база закрывает не
  # мгновенно, и обычное удаление на них спотыкалось — временная база
  # оставалась лежать. База своя, рвутся только её собственные сессии.
  if [[ -n "$БАЗА_ЕСТЬ" ]]; then
    dropdb -h 127.0.0.1 -p $ПОРТ_БАЗЫ -U $ХОЗЯИН --if-exists --force $LOAD_DB_NAME \
      || echo "Временную базу $LOAD_DB_NAME удалить не вышло — удалите сами: dropdb -h 127.0.0.1 -p $ПОРТ_БАЗЫ -U $ХОЗЯИН $LOAD_DB_NAME"
  fi
  return 0
}
trap убрать EXIT
trap 'exit 130' INT TERM

createdb -h 127.0.0.1 -p $ПОРТ_БАЗЫ -U $ХОЗЯИН $LOAD_DB_NAME
БАЗА_ЕСТЬ=1
ЖУРНАЛ=$(mktemp -t partut-load)
$ПИТОН $ЗДЕСЬ/stand.py $ПОРТ > $ЖУРНАЛ 2>&1 &
СТЕНД=$!
# Ждём свой стенд: порт слушает именно он, а не кто-то, кто занял порт раньше.
готов=""
for i in $(seq 1 240); do
  kill -0 $СТЕНД 2>/dev/null || break
  if [[ "$(слушает $ПОРТ)" == "$СТЕНД" ]] && curl -s -m 2 -o /dev/null http://127.0.0.1:$ПОРТ/__load/meta; then готов=1; break; fi
  sleep 1
done
[[ -n "$готов" ]] || { echo "стенд не поднялся на порту $ПОРТ:"; tail -20 $ЖУРНАЛ; exit 1; }
grep "товаров на точках" $ЖУРНАЛ
$ПИТОН $ЗДЕСЬ/run.py http://127.0.0.1:$ПОРТ $ИТОГ
echo "ошибок сервера в журнале стенда: $(grep -c 'ОШИБКА' $ЖУРНАЛ || true) (журнал: $ЖУРНАЛ)"
