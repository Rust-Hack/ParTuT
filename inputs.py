"""
inputs.py — превращение того, что прислал клиент, в то, с чем можно работать.

Листовой модуль: не импортирует ничего своего. Один и тот же разбор нужен всем
ручкам, и пока он жил в server.py, каждая из них тянула за собой всё
приложение.

Правило здесь одно на все функции: НИЧЕГО не роняем. Ручка обязана ответить
внятным отказом, а не пятисоткой, — иначе человек видит «что-то пошло не так»
там, где ему полагалось «заполните поле». Пятисотка вдобавок шлёт владельцу
письмо о сбое: любой желающий мог бы завалить ему почту, зная адрес.
"""


def _text(value, limit=None):
    """Строка из того, что прислал клиент, — что бы он ни прислал.

    Раньше по всему серверу стояло `(data.get("x") or "").strip()`. Приложение
    шлёт строку, и всё работало; но стоило прийти списку или числу — обработчик
    падал с 500. Причём каждое такое падение ещё и отправляло разработчику
    письмо о сбое, то есть любой желающий мог завалить почту, зная адрес.
    Списки и словари строкой не считаем: это не «текст с опечаткой», а мусор.
    """
    if value is None or isinstance(value, (dict, list, tuple, set)):
        return ""
    s = value if isinstance(value, str) else str(value)
    # Нулевой байт: SQLite его молча глотает, а Postgres отказывается принимать
    # такую строку вовсе — и запрос падает с 500. Пришёл он из адреса или из
    # тела, для нас это мусор в любом случае.
    s = s.replace("\x00", "").strip()
    return s[:limit] if limit else s


def _digits(s):
    return "".join(ch for ch in (s or "") if ch.isdigit())


def _num(value, default, as_int=False):
    """Число из настройки. Настройки хранятся строками, и мусор в них не должен
    ронять целый экран — возвращаем то, что задумано по умолчанию."""
    if value is None or value == "":
        return default
    try:
        n = float(str(value).replace(",", "."))
    except (TypeError, ValueError):
        return default
    return int(n) if as_int else n
