"""Пул соединений с Postgres: тёплые соединения переиспользуются, мёртвые — нет.

Нагрузка на копии (8.10.2026): psycopg2 держит про запас ровно minconn
свободных соединений, а сверх того закрывает их при возврате. У нас minconn
был 1 — и при двух одновременных запросах каждое следующее соединение
открывалось заново (шифрование, пароль, новый процесс на базе) и после запроса
закрывалось. Двести входов покупателя подряд — двести новых подключений, под
нагрузкой у сервера кончились порты.

Только Postgres: на SQLite пула нет, файл открывается заново всегда.
"""
from _common import db, Checker


def _pid(conn):
    cur = conn.cursor()
    cur.execute("SELECT pg_backend_pid() AS pid")
    return cur.fetchone()["pid"]


def run_тёплые_переиспользуются():
    if not db.USE_PG:
        print("пропуск: пул есть только у Postgres")
        return []
    c = Checker("Пул: одновременные соединения не открываются заново")
    процессы = set()
    for _ in range(20):
        # Четыре соединения разом — как приложение при открытии (вход,
        # витрина, точки, категории) и фоновая запись поверх.
        разом = [db.connect() for _ in range(4)]
        процессы |= {_pid(x) for x in разом}
        for x in разом:
            x.close()
    c(f"20 раз по 4 соединения разом — процессов базы {len(процессы)}, не больше {db.ТЁПЛЫХ}",
      len(процессы) <= db.ТЁПЛЫХ)
    return c.fails


def run_мёртвое_после_простоя_заменяется():
    if not db.USE_PG:
        print("пропуск: пул есть только у Postgres")
        return []
    c = Checker("Пул: соединение, умершее в пуле, не достаётся запросу")
    # Два соединения в пул: сверху «живое», под ним — то, которое убьём.
    жертва, сверху = db.connect(), db.connect()
    убитый = _pid(жертва)
    жертва.close(); сверху.close()
    палач = db.connect()                   # берёт верхнее, «жертва» остаётся лежать
    cur = палач.cursor()
    cur.execute("SELECT pg_terminate_backend(%s) AS ok", (убитый,))
    c("процесс базы под соединением убит, пока оно лежало в пуле", cur.fetchone()["ok"] is True)
    палач.commit()

    было = db.ПРОВЕРЯТЬ_ПОСЛЕ_СЕК
    db.ПРОВЕРЯТЬ_ПОСЛЕ_СЕК = 0             # «пролежало дольше порога» — без ожидания в тесте
    try:
        выданное = db.connect()            # сверху лежит именно убитое
        try:
            pid = _pid(выданное)
            c(f"запрос получил живое соединение (процесс {pid}, убитый был {убитый})", pid != убитый)
        except Exception as e:
            c(f"запрос получил мёртвое соединение: {type(e).__name__}", False)
        finally:
            выданное.close()
    finally:
        db.ПРОВЕРЯТЬ_ПОСЛЕ_СЕК = было
        палач.close()
    return c.fails


def run_после_перезапуска_базы():
    """Сервер стартовал и открыл тёплые соединения, потом ночь без покупателей,
    и базу за это время перезапустили. Первый утренний запрос не должен
    получить соединение, умершее ночью."""
    if not db.USE_PG:
        print("пропуск: пул есть только у Postgres")
        return []
    c = Checker("Пул: база перезапустилась, пока соединения лежали с самого старта")
    db._POOL.closeall()
    db._POOL = None
    db._get_pool()                                     # пул как при старте сервера
    # Номера процессов базы у лежащих соединений — без обращения к ней.
    лежат = [raw.get_backend_pid() for raw in db._POOL._pool]
    c(f"при старте открыто {len(лежат)} тёплых соединений", len(лежат) == db.ТЁПЛЫХ)
    снаружи = db.psycopg2.connect(db.DATABASE_URL)
    снаружи.autocommit = True
    cur = снаружи.cursor()
    cur.execute("SELECT COUNT(*) FROM (SELECT pg_terminate_backend(pid) FROM unnest(%s::int[]) AS pid) AS x",
                (лежат,))
    снаружи.close()

    было = db.ПРОВЕРЯТЬ_ПОСЛЕ_СЕК
    db.ПРОВЕРЯТЬ_ПОСЛЕ_СЕК = 0                         # «пролежали всю ночь»
    try:
        выданное = db.connect()
        try:
            pid = _pid(выданное)
            c(f"первый запрос получил живое соединение (процесс {pid}, убитые {sorted(лежат)})", pid not in лежат)
        except Exception as e:
            c(f"первый запрос получил мёртвое соединение: {type(e).__name__}", False)
        finally:
            выданное.close()
    finally:
        db.ПРОВЕРЯТЬ_ПОСЛЕ_СЕК = было
    return c.fails
