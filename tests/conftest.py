"""
conftest.py — общая настройка pytest.

Стенд здесь свой и написан раньше pytest: каждый файл держит функцию run(),
которая печатает ✅/❌ и возвращает список непрошедших проверок. Переписывать
шестьдесят восемь файлов разом ради нового запускателя — работа на неделю с
шансом что-нибудь потерять по дороге.

Поэтому pytest подхватывает их как есть: каждая run()/run_что-нибудь()
становится отдельным тестом. Что это даёт сразу, без единой правки в самих
проверках:

  • pytest --lf              — перезапустить только упавшие;
  • pytest -k заказ          — гонять по имени;
  • понятный отчёт с местом падения вместо простыни из печати.

Чего это НЕ даёт: параллельного прогона. Проверки делят одну базу и подменяют
общие имена (auth.get_admin), и запуск их вразнобой сейчас сломает их же.
Разделение состояния — следующий шаг, файл за файлом, а не разом.

Старый запуск при этом жив: `python tests/run_all.py` печатает ту же сводку и
по-прежнему стоит в CI. Два входа в одно и то же — намеренно, пока переезд не
закончен.
"""
