def pytest_pycollect_makeitem(collector, name, obj):
    """Превращает run() и run_*() в обычные тесты pytest."""
    if not (name == "run" or name.startswith("run_")) or not callable(obj):
        return None
    if not getattr(obj, "__module__", "").startswith("test_"):
        return None
    return pytest.Function.from_parent(collector, name=name, callobj=_как_тест(obj))


def _как_тест(функция):
    def проверка():
        падения = функция() or []
        assert not падения, ("не прошли проверки:\n"
                             + "\n".join(f"  • {п}" for п in падения))
    проверка.__name__ = функция.__name__
    проверка.__doc__ = функция.__doc__
    return проверка


