"""Окно «📦 Склад» — что экран ОТПРАВИТ. Серверные тесты этого не видят.

Приёмка 30 сентября 2026 нашла три ошибки, которые жили только в экране:
пересчёт уходил, пока невыданные заказы ещё грузились (S-01); после отказа
«уже записано» следующий тап отправлял число как новый приход (S-02); у
заказа с двумя вкусами было две галочки, а в расчёт шла одна (S-03).

Сами проверки — в tests/js/stock_dialog.cjs: настоящий код окна из
04-admin.js в песочнице Node с подменой экрана и сети. Здесь — только запуск,
чтобы они шли в общем прогоне и в CI.

Проверка, которая «прошла», потому что ничего не запустила, хуже упавшей: без
Node или с меньшим числом проверок, чем ожидается, — это провал, а не пропуск.
"""
import os
import shutil
import subprocess

from _common import Checker

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СКРИПТ = os.path.join(КОРЕНЬ, "tests", "js", "stock_dialog.cjs")
НЕ_МЕНЬШЕ = 19          # столько проверок в скрипте сейчас; меньше — что-то выпало


def run():
    c = Checker("Окно склада: что уходит на сервер")
    node = shutil.which("node")
    c("Node установлен (без него проверки экрана не запустить)", bool(node))
    if not node:
        return c.fails
    r = subprocess.run([node, СКРИПТ], capture_output=True, text=True, timeout=60, cwd=КОРЕНЬ)
    вывод = r.stdout + r.stderr
    прошли = вывод.count("✅")
    не_прошли = [строка for строка in вывод.splitlines() if строка.startswith("❌")]
    for строка in не_прошли:
        c(строка[2:].strip(), False)
    c(f"все проверки прошли (код выхода {r.returncode})", r.returncode == 0 and not не_прошли)
    c(f"проверок не меньше {НЕ_МЕНЬШЕ} (прошло {прошли})", прошли >= НЕ_МЕНЬШЕ)
    return c.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
