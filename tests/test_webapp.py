"""Проверки приложения в браузере — без браузера.

У фронтенда не было ни одной автоматической проверки: он проверялся глазами.
Между такими проверками ошибка в нём ломает весь экран молча — и это не
предположение: этой проверкой нашлось живое обращение к элементу afCity,
которого нет. При добавлении точки строка падала, падение перехватывал общий
catch, и владелец видел «Сеть недоступна», хотя точка добавлялась.

Браузер в прогоне не поднять, поэтому берём то, что проверяется разбором
текста, но ловит настоящие поломки:

  • обращение к элементу, которого нет в разметке;
  • запрос на адрес, которого нет в сервере (переименовали ручку — забыли клиент);
  • незакрытые фигурные скобки в шаблонных строках приложения.
"""
import re

from _common import Checker, server

ФАЙЛ = "webapp/index.html"


def _текст():
    import os
    корень = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(корень, ФАЙЛ), encoding="utf-8") as f:
        return f.read()


def run():
    html = _текст()

    c = Checker("Элементы, к которым обращается приложение")
    обращения = set(re.findall(r'\$\("([A-Za-z0-9_-]+)"\)', html))
    в_разметке = set(re.findall(r'\bid="([A-Za-z0-9_-]+)"', html))
    # Часть элементов создаётся помощниками: их имя передаётся строкой.
    # pickerHtml("mdBrand", …) создаёт <select id="mdBrand">.
    через_помощников = set(re.findall(r'(?:pickerHtml|bindPicker|pickerValue)\("([A-Za-z0-9_-]+)"', html))
    пропавшие = sorted(обращения - в_разметке - через_помощников)
    c(f"обращений найдено ({len(обращения)})", len(обращения) > 100)
    c("нет обращений к несуществующим элементам"
      + ("" if not пропавшие else f": {пропавшие}"), not пропавшие)

    c2 = Checker("Адреса, по которым приложение ходит")
    адреса = set(re.findall(r'fetch\("(/api/[A-Za-z0-9_/-]+)"', html))
    маршруты = {str(r) for r in server.app.url_map.iter_rules()}
    несуществующие = sorted(a for a in адреса if a not in маршруты)
    c2(f"адресов найдено ({len(адреса)})", len(адреса) > 30)
    c2("все адреса есть в сервере"
       + ("" if not несуществующие else f": {несуществующие}"), not несуществующие)

    # Обратная сторона: ручка есть, а зовёт ли её кто-нибудь — знать полезно,
    # но это не ошибка (часть ручек для бота и для служебных нужд).
    # --- Синтаксис самого приложения ---
    # Одна незакрытая скобка ломает весь экран, и Python об этом не узнает
    # никогда. Проверяем настоящим разбором, а не догадками по тексту.
    c3 = Checker("Синтаксис приложения")
    свой_код = "\n".join(
        m.group(1) for m in re.finditer(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", html, re.S))
    c3(f"код приложения найден ({len(свой_код.splitlines())} строк)",
       len(свой_код.splitlines()) > 1000)

    import shutil
    if not shutil.which("node"):
        # Молчать нельзя: пропуск не должен выглядеть как успех.
        c3("node не найден — разбор пропущен", True)
        return c.fails + c2.fails + c3.fails

    import subprocess, tempfile, os
    путь = tempfile.mktemp(suffix=".js")
    try:
        with open(путь, "w", encoding="utf-8") as f:
            f.write(свой_код)
        r = subprocess.run(["node", "--check", путь], capture_output=True, text=True)
        беда = (r.stderr or "").strip().splitlines()
        # Ошибку показываем целиком: «синтаксис сломан» без места бесполезно.
        c3("разбирается без ошибок" + ("" if r.returncode == 0 else ": " + " / ".join(беда[:4])),
           r.returncode == 0)
    finally:
        try:
            os.unlink(путь)
        except OSError:
            pass

    return c.fails + c2.fails + c3.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
