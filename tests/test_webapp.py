"""Проверки приложения в браузере — без браузера.

У фронтенда не было ни одной автоматической проверки: он проверялся глазами.
Между такими проверками ошибка в нём ломает весь экран молча — и это не
предположение: этой проверкой нашлось живое обращение к элементу afCity,
которого нет. При добавлении точки строка падала, падение перехватывал общий
catch, и владелец видел «Сеть недоступна», хотя точка добавлялась.

Браузер в прогоне не поднять, поэтому берём то, что проверяется разбором
текста, но ловит настоящие поломки:

  • обращение к элементу, которого нет в разметке;
  • запрос на адрес, которого нет в сервере (переименовали ручку — забыли клиент);
  • незакрытые фигурные скобки в шаблонных строках приложения.

Разбираем не файл с диска, а страницу, СОБРАННУЮ сервером из разметки, стилей
и кода. Так проверка смотрит ровно на то, что уходит покупателю: не склеься
куски — это увидится здесь, а не в чужом телефоне.
"""
import re

from _common import Checker, server


def _текст():
    """Страница целиком — как её отдаёт сервер."""
    return server._index_payload()["raw"].decode("utf-8")


def run():
    html = _текст()

    c0 = Checker("Приложение собирается из кусков целиком")
    c0("метки подстановки не остались в странице",
       "{{СТИЛИ}}" not in html and "{{ПРИЛОЖЕНИЕ}}" not in html)
    c0("стили попали в страницу", "--glow-rgb" in html)
    c0("код попал в страницу", "function start(" in html)
    c0("разметка на месте", 'id="splash"' in html)

    # Ни один кусок не должен потеряться по дороге. Потеряйся — приложение
    # откроется без части кода и сломается молча, в чужом телефоне.
    import os
    куски = server._app_parts()
    c0(f"кусков приложения найдено ({len(куски)})", len(куски) >= 2)
    for путь in куски:
        with open(путь, encoding="utf-8") as f:
            тело = [s.rstrip() for s in f.read().splitlines()
                    if s.strip() and not s.strip().startswith("//")]
        целиком = all(s in html for s in тело)
        c0(f"{os.path.basename(путь)} попал в страницу целиком ({len(тело)} строк)", целиком)

    # Порядок склейки берётся из имени, поэтому имя обязано его задавать.
    # Кусок без номера встал бы в произвольное место — это одна программа,
    # разложенная по файлам, и порядок в ней значит ровно то же, что и раньше.
    import re as _re
    безымянные = [os.path.basename(п) for п in куски
                  if not _re.match(r"^\d\d-", os.path.basename(п))]
    c0("у каждого куска номер в имени, он же порядок склейки"
       + ("" if not безымянные else f": {безымянные}"), not безымянные)

    c = Checker("Элементы, к которым обращается приложение")
    обращения = set(re.findall(r'\$\("([A-Za-z0-9_-]+)"\)', html))
    в_разметке = set(re.findall(r'\bid="([A-Za-z0-9_-]+)"', html))
    # Часть элементов создаётся помощниками: их имя передаётся строкой.
    # pickerHtml("mdBrand", …) создаёт <select id="mdBrand">.
    через_помощников = set(re.findall(r'(?:pickerHtml|bindPicker|pickerValue)\("([A-Za-z0-9_-]+)"', html))
    пропавшие = sorted(обращения - в_разметке - через_помощников)
    c(f"обращений найдено ({len(обращения)})", len(обращения) > 100)
    c("нет обращений к несуществующим элементам"
      + ("" if not пропавшие else f": {пропавшие}"), not пропавшие)

    c2 = Checker("Адреса, по которым приложение ходит")
    адреса = set(re.findall(r'fetch\("(/api/[A-Za-z0-9_/-]+)"', html))
    маршруты = {str(r) for r in server.app.url_map.iter_rules()}
    несуществующие = sorted(a for a in адреса if a not in маршруты)
    c2(f"адресов найдено ({len(адреса)})", len(адреса) > 30)
    c2("все адреса есть в сервере"
       + ("" if not несуществующие else f": {несуществующие}"), not несуществующие)

    # Обратная сторона: ручка есть, а зовёт ли её кто-нибудь — знать полезно,
    # но это не ошибка (часть ручек для бота и для служебных нужд).
    # --- Синтаксис самого приложения ---
    # Одна незакрытая скобка ломает весь экран, и Python об этом не узнает
    # никогда. Проверяем настоящим разбором, а не догадками по тексту.
    c3 = Checker("Синтаксис приложения")
    свой_код = "\n".join(
        m.group(1) for m in re.finditer(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", html, re.S))
    c3(f"код приложения найден ({len(свой_код.splitlines())} строк)",
       len(свой_код.splitlines()) > 1000)

    import shutil
    if not shutil.which("node"):
        # Молчать нельзя: пропуск не должен выглядеть как успех.
        c3("node не найден — разбор пропущен", True)
        return c0.fails + c.fails + c2.fails + c3.fails

    import subprocess, tempfile, os
    путь = tempfile.mktemp(suffix=".js")
    try:
        with open(путь, "w", encoding="utf-8") as f:
            f.write(свой_код)
        r = subprocess.run(["node", "--check", путь], capture_output=True, text=True)
        беда = (r.stderr or "").strip().splitlines()
        # Ошибку показываем целиком: «синтаксис сломан» без места бесполезно.
        c3("разбирается без ошибок" + ("" if r.returncode == 0 else ": " + " / ".join(беда[:4])),
           r.returncode == 0)
    finally:
        try:
            os.unlink(путь)
        except OSError:
            pass

    return c0.fails + c.fails + c2.fails + c3.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)


def run_js_syntax():
    """Куски приложения обязаны быть синтаксически целыми.

    Питон проверяет линтер, а JavaScript до сих пор не проверял никто: сборка
    страницы — это склейка текста, и файл с синтаксической ошибкой доезжает до
    браузера как есть. Ломается при этом ВСЁ приложение сразу, а на сервере
    тихо: он отдал 200 и доволен.

    Написано после того, как в комментарии посреди рабочего кода оказалась
    решётка вместо двух косых. Заметить это глазами при беглом чтении нельзя.
    """
    import os
    import shutil
    import subprocess

    c = Checker("Синтаксис приложения")
    узел = shutil.which("node")
    if not узел:
        # Молчать нельзя: пропуск, выглядящий как успех, — та же беда, ради
        # которой этот файл и написан.
        c("node не найден — проверка НЕ ВЫПОЛНЕНА, поставьте node", False)
        return c.fails

    куски = server._app_parts()
    c(f"куски найдены ({len(куски)})", len(куски) >= 2)
    for путь in куски:
        готово = subprocess.run([узел, "--check", путь], capture_output=True, text=True)
        # Из вывода node берём строку с самой ошибкой, а не последнюю: в конце
        # он печатает свою версию, и сообщение «упало: Node.js v24» не говорит
        # ничего. Полезное — строка SyntaxError и номер строки перед ней.
        строки = (готово.stderr or "").strip().splitlines()
        беда = next((с.strip() for с in строки if "Error" in с), "")
        место = next((с.strip() for с in строки if ".js:" in с), "")
        c(f"{os.path.basename(путь)} без синтаксических ошибок"
          + ("" if готово.returncode == 0 else f": {место} · {беда}"),
          готово.returncode == 0)
    return c.fails
