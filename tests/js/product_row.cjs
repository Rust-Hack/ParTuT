// Те же помощники, что в приложении (01-core.js, 04-admin.js), — в коротком виде.
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
function plural(n, one, few, many) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}
const СЛОВА = { liquid: "Вкус", coils: "Сопротивление", podsystem: "Цвет", snus: "Крепость" };

function стенд(товары, настройки = {}) {
  const узлы = new Map();
  const $ = (id) => {
    if (!узлы.has(id)) узлы.set(id, { textContent: "", innerHTML: "", querySelectorAll: () => [] });
    return узлы.get(id);
  };
  const сомнения = new Set(настройки.сомнения || []);
  const ctx = vm.createContext({
    $, esc, plural, LOW_STOCK: 3,
    shelf: () => товары,
    myScope: () => настройки.точкаПродавца || null,
    admSearch: настройки.поиск || "", admCatFilter: настройки.категория || "all",
    admLocFilter: настройки.точка || "all", admStockFilter: настройки.остаток || "all",
    stockState: (p) => p.stock <= 0 ? "out" : (p.stock <= 3 ? "low" : "ok"),
    hasVariants: (p) => !!(p.variants && p.variants.length),
    catVariant: (code) => СЛОВА[code] || "Вкус",
    locations: настройки.точки || [{ name: "Минск" }, { name: "Туров" }, { name: "Лунинец" }],
    ценаСомнительна: (id) => сомнения.has(id),
    открытьЦену() {}, openStockMove() {}, openEdit() {}, открытьЕщё() {},
    // Товары, которые нигде не продаются (описание без точек), — блок внизу.
    isOwner: () => !!настройки.владелец, models: настройки.модели || [],
    админСписокСвеж: настройки.списокСвеж !== false, витринаСвежа: настройки.витринаСвежа !== false, послеАрхива: async () => true,
    админГрузится: настройки.грузится || 0,
    полноеИмя: (б, н) => { б = String(б || "").trim(); н = String(н || "").trim();
      return !б ? н : !н ? б : н.toLowerCase().startsWith(б.toLowerCase()) ? н : `${б} ${н}`; },
    catName: (c) => c, openStockIn() {}, открытьОписание() {}, delModel() {},
  });
  vm.runInContext(require("./_search.cjs") + "\n" + код, ctx);      // поиск — настоящий (ROLE-04/05)
  if (настройки.архив) { ctx.__архив = настройки.архив; vm.runInContext("архивТоваров = __архив", ctx); }
  ctx.__состояние = настройки.архивСостояние || "ok";
  vm.runInContext("архивСостояние = __состояние", ctx);
  if (настройки.архивОткрыт) vm.runInContext("архивОткрыт = true", ctx);
  (настройки.раскрыты || []).forEach(к => vm.runInContext(`раскрытыеГруппы.add(${JSON.stringify(к)})`, ctx));
  vm.runInContext("нарисоватьСписокТоваров()", ctx);
  const html = $("adminList").innerHTML;
  // Строки по отдельности и их видимый текст (неразрывные пробелы — обычные).
  const строки = html.split('<div class="admrow prodrow').slice(1).map((кусок) => ({
    html: кусок,
    текст: кусок.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/\s+/g, " ").trim(),
  }));
  const группы = html.split('<div class="admrow prodgroup').slice(1).map((кусок) =>
    кусок.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim());
  return { html, строки, группы, счёт: $("admCount").textContent };
}

