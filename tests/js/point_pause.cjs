// «Закрыта ли точка сейчас» у покупателя — настоящий код из 01-core.js
// (паузаТочки, перечитатьТочки, обновитьБаннерПаузы).
//
// Список точек сервер кэширует на 5 минут, поэтому время вышло — точка уже
// открыта по часам телефона; без времени — закрыта, пока не откроют. А
// открыли раньше времени — покупатель узнаёт это перечитыванием (по кнопке,
// при возврате в корзину и в приложение): раньше «Оформить» оставалось
// выключенным до перезагрузки (приёмка PS-03). Не ответил сервер — точка
// остаётся закрытой. Последнее слово — за оформлением на сервере
// (tests/test_point_pause.py).
//
// Запуск: node tests/js/point_pause.cjs — печатает ✅/❌, код выхода 1 при ❌.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const исходник = fs.readFileSync(path.join(__dirname, "..", "..", "partut", "webapp", "app", "01-core.js"), "utf8");
const а = исходник.indexOf("function паузаТочки(name)");
const б = исходник.indexOf("\nfunction renderGrid()", а);
if (а < 0 || б < 0) { console.log("❌ не нашёл код паузы в 01-core.js"); process.exit(1); }

let провалов = 0, дошлиДоКонца = false;
process.on("exit", () => { if (!дошлиДоКонца) { console.log("❌ проверки не дошли до конца"); process.exitCode = 1; } });
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}

const сейчас = 1_790_000_000_000;
function стенд(точки, сеть) {
  const баннер = { hidden: true, innerHTML: "" };
  const таймеры = [];
  const ctx = vm.createContext({
    Date: { now: () => ctx.__сейчас }, __сейчас: сейчас, Math, JSON, точкиПрочитаны: сейчас,
    locations: JSON.parse(JSON.stringify(точки)), city: "Минск", activeTab: "cart",
    $: (id) => (id === "pauseBanner" ? баннер : null), esc: (x) => String(x ?? ""),
    document: { addEventListener() {}, visibilityState: "visible" },
    setTimeout: (f, мс) => { таймеры.push({ f, мс }); return таймеры.length; }, clearTimeout() {},
    renderCart: () => { ctx.__корзина = (ctx.__корзина || 0) + 1; },
    fetchLocations: async () => {
      const ответ = сеть.shift();
      if (ответ === "сбой") return false;
      ctx.locations = ответ;
      ctx.точкиПрочитаны = ctx.__сейчас;      // как настоящая: отметка — только при успехе
      return true;
    },
  });
  vm.runInContext(исходник.slice(а, б), ctx);
  return { ctx, баннер, таймеры, js: (к) => vm.runInContext(к, ctx) };
}

(async () => {
  // ---- Закрыта ли сейчас ----
  {
    const с = стенд([
      { name: "Минск", closed: null },
      { name: "Туров", closed: { until_ms: сейчас + 60_000, words: "до 18:01", note: "обед" } },
      { name: "Лунинец", closed: { until_ms: сейчас - 1, words: "до 18:00", note: "" } },
      { name: "Горки", closed: { until_ms: null, words: "пока не откроют", note: "" } },
    ], []);
    const п = (имя) => с.js(`паузаТочки(${JSON.stringify(имя)})`);
    проверка("открытая точка — паузы нет", п("Минск") === null);
    проверка("закрыта на минуту вперёд — пауза со словами и заметкой", п("Туров") && п("Туров").words === "до 18:01" && п("Туров").note === "обед");
    проверка("время открытия уже прошло — открыта, не дожидаясь свежего списка", п("Лунинец") === null);
    проверка("без времени — закрыта, пока не откроют", п("Горки") && п("Горки").words === "пока не откроют");
    проверка("неизвестная точка — паузы нет", п("Нигдеград") === null);
  }

  // ---- PS-03: открыли раньше — покупатель узнаёт без перезагрузки ----
  const закрыта = [{ name: "Минск", closed: { until_ms: null, words: "пока не откроют", note: "" } }];
  const открыта = [{ name: "Минск", closed: null }];
  {
    const с = стенд(закрыта, [открыта]);
    с.js("обновитьБаннерПаузы()");
    проверка("закрыта бессрочно — баннер виден", с.баннер.hidden === false);
    const ок = await с.js("перечитатьТочки(true)");
    проверка("перечитали — точка открыта, баннер убран, корзина перерисована",
      ок === true && с.js("паузаТочки('Минск')") === null && с.баннер.hidden === true && с.ctx.__корзина >= 1);
  }
  {
    const с = стенд(закрыта, ["сбой"]);
    const ок = await с.js("перечитатьТочки(true)");
    проверка("сервер не ответил — точка остаётся закрытой (открытой её объявляет только сервер)",
      ок === false && с.js("паузаТочки('Минск')") !== null);
  }
  {
    const с = стенд(закрыта, [открыта]);
    проверка("переход по вкладкам чаще раза в 5 с — сеть не дёргаем", (await с.js("перечитатьТочки()")) === null);
    с.ctx.__сейчас = сейчас + 6_000;
    проверка("…а через 5 с — перечитываем", (await с.js("перечитатьТочки()")) === true && с.js("паузаТочки('Минск')") === null);
  }
  // ---- Время открытия наступает, пока приложение открыто ----
  {
    const с = стенд([{ name: "Минск", closed: { until_ms: сейчас + 60_000, words: "до 18:01", note: "" } }], [открыта]);
    с.js("обновитьБаннерПаузы()");
    const т = с.таймеры.at(-1);
    проверка("поставлен таймер на время открытия (+1.5 с)", т && т.мс === 61_500, т && т.мс);
    с.ctx.__сейчас = сейчас + 61_500;
    await т.f();
    проверка("таймер сработал — перечитали, точка открыта, баннер убран", с.js("паузаТочки('Минск')") === null && с.баннер.hidden === true);
  }

  // ---- PS-03-R1: время вышло, а проверить не вышло — точка остаётся закрытой ----
  {
    const продлена = [{ name: "Минск", closed: { until_ms: сейчас + 3_600_000, words: "до 19:00", note: "" } }];
    const с = стенд([{ name: "Минск", closed: { until_ms: сейчас + 60_000, words: "до 18:01", note: "" } }], ["сбой", продлена]);
    с.js("обновитьБаннерПаузы()");
    с.ctx.__сейчас = сейчас + 61_500;
    await с.таймеры.at(-1).f();                     // срок вышел, перечитать не удалось
    проверка("срок вышел, перечитать не удалось — точка по-прежнему закрыта, баннер виден",
      с.js("паузаТочки('Минск')") !== null && с.баннер.hidden === false);
    проверка("следующая попытка — через 30 с, а не каждую секунду", с.таймеры.at(-1).мс === 30000, с.таймеры.at(-1).мс);
    await с.js("перечитатьТочки(true)");             // связь вернулась: продавец продлил до 19:00
    проверка("связь вернулась — видна продлённая пауза «до 19:00», а не «открыта»",
      с.js("паузаТочки('Минск')") && с.js("паузаТочки('Минск').words") === "до 19:00");
  }

  дошлиДоКонца = true;
  console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
  process.exit(провалов ? 1 : 0);
})();
