// «Закрыта ли точка сейчас» у покупателя — настоящая паузаТочки из 01-core.js.
// Список точек сервер кэширует на 5 минут, поэтому время вышло — точка уже
// открыта по часам телефона, не дожидаясь свежего списка; без времени —
// закрыта, пока не откроют. Последнее слово — за оформлением на сервере
// (tests/test_point_pause.py).
//
// Запуск: node tests/js/point_pause.cjs — печатает ✅/❌, код выхода 1 при ❌.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const исходник = fs.readFileSync(path.join(__dirname, "..", "..", "partut", "webapp", "app", "01-core.js"), "utf8");
const а = исходник.indexOf("function паузаТочки(name)");
const б = исходник.indexOf("\nfunction обновитьБаннерПаузы()", а);
if (а < 0 || б < 0) { console.log("❌ не нашёл паузаТочки в 01-core.js"); process.exit(1); }

let провалов = 0;
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}
const сейчас = 1_790_000_000_000;
const ctx = vm.createContext({ Date: { now: () => сейчас }, locations: [
  { name: "Минск", closed: null },
  { name: "Туров", closed: { until_ms: сейчас + 60_000, words: "до 18:01", note: "обед" } },
  { name: "Лунинец", closed: { until_ms: сейчас - 1, words: "до 18:00", note: "" } },
  { name: "Горки", closed: { until_ms: null, words: "пока не откроют", note: "" } },
] });
vm.runInContext(исходник.slice(а, б), ctx);
const п = (имя) => vm.runInContext(`паузаТочки(${JSON.stringify(имя)})`, ctx);
проверка("открытая точка — паузы нет", п("Минск") === null);
проверка("закрыта на минуту вперёд — пауза со словами и заметкой", п("Туров") && п("Туров").words === "до 18:01" && п("Туров").note === "обед");
проверка("время открытия уже прошло — открыта, не дожидаясь свежего списка", п("Лунинец") === null);
проверка("без времени — закрыта, пока не откроют", п("Горки") && п("Горки").words === "пока не откроют");
проверка("неизвестная точка — паузы нет", п("Нигдеград") === null);
console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
process.exit(провалов ? 1 : 0);
