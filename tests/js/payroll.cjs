// «💰 Зарплата продавцов» — настоящий код из 04-admin.js в песочнице Node.
//
// Приёмка DAY-02, решение владельца 7.10.2026: выплату отмечают только за
// закончившийся месяц, а разница после поздней отмены переходит в ближайшую
// выплату отдельной строкой. Раньше экран показывал рядом «10% — к выплате
// 1.00 Br» и «выплачено 2.00 Br», и было непонятно, начисление это или долг.
// Здесь проверяется, что каждое состояние подписано словами: месяц идёт —
// «можно отметить с 1 ноября» и без кнопки; закончился — из чего складывается
// «к выплате»; выплачен — сколько и что изменилось после.
//
// Запуск: node tests/js/payroll.cjs — печатает ✅/❌, код выхода 1 при ❌.
// Из pytest его зовёт tests/test_js_handlers.py.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const админка = fs.readFileSync(path.join(__dirname, "..", "..", "partut", "webapp", "app", "04-admin.js"), "utf8");
function кусок(текст, от, до) {
  const а = текст.indexOf(от), б = текст.indexOf(до, а);
  if (а < 0 || б < 0) { console.log(`❌ не нашёл: ${от}`); process.exit(1); }
  return текст.slice(а, б);
}
const код = кусок(админка, "// ----- Зарплата продавцов", "// ----- Розыгрыш (админ) -----");

let провалов = 0, дошлиДоКонца = false;
process.on("exit", () => {
  if (!дошлиДоКонца) { console.log("❌ проверки не дошли до конца — что-то упало"); process.exitCode = 1; }
});
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}

// ответы: (тело) => ответ сервера на /api/admin/payroll; можно вернуть Promise.
function стенд(ответы, { владелец = true, часы = "2026-10-15T12:00:00", пост = null } = {}) {
  const узлы = {};
  const $ = (id) => узлы[id] || (узлы[id] = { id, innerHTML: "", textContent: "", disabled: false,
    classList: { add() {}, remove() {}, contains: () => true }, querySelectorAll: () => [], querySelector: () => null });
  const вопросы = [], тосты = [], запросы = [], посты = [];
  const Настоящая = Date;
  class Часы extends Настоящая { constructor(...а) { super(...(а.length ? а : [часы])); } }
  const ctx = vm.createContext({
    $, console, JSON, Math, Promise, Object, Array, String, Number, Date: Часы, initData: "qa",
    CUR: `<span class="cur">Br</span>`,             // как в 01-core.js: в тексте вопроса разметке не место
    isOwner: () => владелец, esc: (s) => String(s ?? "").replace(/</g, "&lt;"), loaderHtml: () => "<загрузка>",
    toast: (m) => тосты.push(m), confirmMsg: (m, да) => { вопросы.push(m); ctx.__да = да(); },
    админПост: async (адрес, тело) => { посты.push({ адрес, тело }); return пост ? пост(тело) : { ok: true, amount: 3 }; },
    fetch: async (url, o) => {
      const тело = JSON.parse(o.body);
      запросы.push({ url, тело });
      const ответ = await ответы(тело);
      return { json: async () => ответ };
    },
  });
  vm.runInContext(код, ctx);
  const js = (к) => vm.runInContext(к, ctx);
  const ждать = async () => { for (let i = 0; i < 6; i++) { await (ctx.__да || null); await new Promise(r => setImmediate(r)); } };
  // Экран сверяем по словам: валюта в нём — разметкой, это нормально для HTML.
  return { ctx, js, узлы, вопросы, тосты, запросы, посты, ждать,
           экран: () => узлы.payrollBody.innerHTML.replace(/<span class="cur">Br<\/span>/g, "Br") };
}
const продавец = (лишнее) => ({ user_id: 7, note: "Лена", former: false, paid: null, paid_elsewhere: null,
                                 carry: [], to_pay: null, settle: [], ...лишнее });
const ответ = (лишнее, люди) => ({ ok: true, period: "2026-09", current: "2026-10", open: false, pay_from: "1 октября",
  rows: [{ city: "Минск", revenue: 50, percent: 10, amount: 5, sellers: люди }], ...лишнее });

(async () => {
  // ---- Месяц идёт: ни суммы к выплате, ни кнопки ----
  {
    const с = стенд(() => ответ({ period: "2026-10", open: true, pay_from: "1 ноября" },
      [продавец({ carry: [{ period: "2026-08", label: "август 2026", amount: -2 }] })]));
    с.js("openPayroll()"); await с.ждать();
    const э = с.экран();
    проверка("идущий месяц: «можно отметить с 1 ноября», кнопки выплаты нет",
      /можно отметить с 1 ноября/.test(э) && !/data-pay=/.test(э), э);
    проверка("…«начислено пока» и «месяц идёт» у продавца", /начислено пока/.test(э) && /месяц идёт/.test(э));
    проверка("…перерасчёт прошлого месяца — отдельной строкой «учтётся при выплате», с минусом",
      /Перерасчёт за август 2026 · учтётся при выплате<\/span><b>−2\.00 Br/.test(э), э);
    проверка("…«›» в будущий месяц закрыт", /id="payrollNext" disabled/.test(э));
  }

  // ---- Закончившийся месяц: из чего «к выплате» ----
  {
    const с = стенд(() => ответ({}, [продавец({ to_pay: 3, settle: [{ period: "2026-08", label: "август 2026", amount: -2 }],
                                                 carry: [{ period: "2026-08", label: "август 2026", amount: -2 }] })]));
    с.js(`payrollPeriod = "2026-09"; loadPayroll()`); await с.ждать();
    const э = с.экран();
    проверка("начислено 5.00, перерасчёт −2.00, «К выплате» 3.00 — тремя строками",
      /Начислено за месяц<\/span><b>5\.00 Br/.test(э) && /Перерасчёт за август 2026<\/span><b>−2\.00 Br/.test(э)
        && /К выплате<\/b><\/span><b>3\.00 Br/.test(э), э);
    проверка("кнопка называет сумму: «Отметить: выплачено 3.00 Br»", /data-pay="Минск::7">Отметить: выплачено 3\.00 Br</.test(э), э);
    проверка("переплата закрыта целиком — про «следующую выплату» ни слова", !/следующую выплату/.test(э));

    с.js(`payNow("Минск::7", { disabled: false, textContent: "" }, ${JSON.stringify(ответ({}, [продавец({ to_pay: 3,
      settle: [{ period: "2026-08", label: "август 2026", amount: -2 }] })]))})`);
    await с.ждать();
    проверка("подтверждение: сумма и состав — «начислено 5.00 Br, перерасчёт за август 2026 −2.00 Br»",
      /выплаченной: 3\.00 Br\?/.test(с.вопросы[0]) && /начислено 5\.00 Br, перерасчёт за август 2026 −2\.00 Br/.test(с.вопросы[0]), с.вопросы[0]);
    проверка("ушло: месяц, точка и продавец — сумму считает сервер",
      JSON.stringify(с.посты[0].тело) === '{"period":"2026-09","city":"Минск","user_id":7}', с.посты[0]);
    проверка("«Отмечено ✓ · 3.00 Br» и экран перечитан", с.тосты.at(-1) === "Отмечено ✓ · 3.00 Br"
      && с.запросы.filter(з => з.url === "/api/admin/payroll").length === 2);
    // Вопрос Telegram и всплывашка показывают текст как есть: <span> вылез бы буквами.
    проверка("в вопросе и во всплывашке нет разметки", !/[<>]/.test(с.вопросы[0]) && !/[<>]/.test(с.тосты.at(-1)), [с.вопросы[0], с.тосты.at(-1)]);
  }

  // ---- Отказ («уже отмечено») — экран всё равно перечитан ----
  {
    const с = стенд(() => ответ({}, [продавец({ to_pay: 5 })]), { пост: () => null });
    с.js("openPayroll()"); await с.ждать();
    с.js(`payNow("Минск::7", { disabled: false, textContent: "" }, null)`);
    await с.ждать();
    проверка("отказ сервера — экран перечитан, а не оставлен с прежней кнопкой",
      с.запросы.filter(з => з.url === "/api/admin/payroll").length === 2 && !с.тосты.length);
  }

  // ---- Переплата больше начисленного ----
  {
    const с = стенд(() => ответ({}, [продавец({ to_pay: 0, settle: [{ period: "2026-09", label: "сентябрь 2026", amount: -3 }],
                                                 carry: [{ period: "2026-09", label: "сентябрь 2026", amount: -5 }] })]));
    с.js("openPayroll()"); await с.ждать();
    const э = с.экран();
    проверка("платить нечего: «Закрыть месяц: выплата 0 Br»", /Закрыть месяц: выплата 0 Br/.test(э), э);
    проверка("…и сказано, что остаток переплаты 2.00 Br перейдёт в следующую выплату",
      /Переплата 2\.00 Br больше начисленного — остаток перейдёт в следующую выплату/.test(э), э);
  }

  // ---- Выплаченный месяц: сколько, из чего, что изменилось после ----
  {
    const с = стенд(() => ответ({}, [продавец({ paid: { amount: 3, base: 5, revenue: 50, percent: 10, created_at: "2026-10-01 09:00",
      corrections: [{ period: "2026-08", label: "август 2026", amount: -2 }], now: 5, diff: 0, settled: [], left: 0 } })]));
    с.js("openPayroll()"); await с.ждать();
    const э = с.экран();
    проверка("«выплачено 3.00 Br · 01.10.2026», начислено 5.00 и перерасчёт «в этой выплате»",
      /выплачено 3\.00 Br · 01\.10\.2026/.test(э) && /Начислено за месяц<\/span><b>5\.00 Br/.test(э)
        && /Перерасчёт за август 2026 — в этой выплате<\/span><b>−2\.00 Br/.test(э), э);
    проверка("ничего не менялось — пояснения о разнице нет", !/После выплаты/.test(э));
  }
  {
    const с = стенд(() => ответ({ period: "2026-08" }, [продавец({ paid: { amount: 2, base: 2, revenue: 20, percent: 10,
      created_at: "2026-09-01 10:00", corrections: [], now: 0, diff: -2, settled: [], left: -2 } })]));
    с.js("openPayroll()"); await с.ждать();
    проверка("продажу отменили после выплаты: «сейчас 0.00 вместо 2.00 (−2.00)… учтётся в ближайшей выплате»",
      /начислено сейчас 0\.00 Br вместо 2\.00 Br \(−2\.00 Br\)\. Разница −2\.00 Br учтётся в ближайшей выплате/.test(с.экран()), с.экран());
  }
  {
    const с = стенд(() => ответ({ period: "2026-08" }, [продавец({ paid: { amount: 2, base: 2, revenue: 20, percent: 10,
      created_at: "2026-09-01 10:00", corrections: [], now: 0, diff: -2, left: 0,
      settled: [{ period: "2026-09", label: "сентябрь 2026", amount: -2 }] } })]));
    с.js("openPayroll()"); await с.ждать();
    проверка("…а когда разницу уже закрыли — «учтена в выплате за сентябрь 2026»",
      /Разница учтена в выплате за сентябрь 2026/.test(с.экран()), с.экран());
  }

  // ---- Бывший продавец и выплата на другой точке ----
  {
    const с = стенд(() => ответ({}, [
      продавец({ user_id: 8, note: "", former: true, paid: { amount: 4, base: 4, revenue: 40, percent: 10, created_at: "2026-10-01 09:00",
        corrections: [], now: 4, diff: 0, settled: [], left: 0 } }),
      продавец({ paid_elsewhere: "Туров" })]));
    с.js("openPayroll()"); await с.ждать();
    const э = с.экран();
    проверка("бывший продавец остаётся в истории с выплатой", /8 <small[^>]*>· больше не продавец этой точки<\/small><\/span><b[^>]*>выплачено 4\.00 Br/.test(э), э);
    проверка("переведённому — «выплачено на точке «Туров»», без второй кнопки",
      /выплачено на точке «Туров»/.test(э) && !/data-pay=/.test(э), э);
  }

  // ---- Опоздавший ответ не перетирает новый месяц ----
  {
    let отпустить;
    const медленно = new Promise(r => { отпустить = r; });
    const с = стенд((тело) => тело.period === "2026-10"
      ? медленно.then(() => ответ({ period: "2026-10", open: true, pay_from: "1 ноября" }, [продавец({})]))
      : ответ({}, [продавец({ to_pay: 5 })]));
    с.js("openPayroll()");
    await new Promise(r => setImmediate(r));
    с.узлы.payrollPrev.onclick();
    await с.ждать();
    отпустить(); await с.ждать();
    проверка("листнул на сентябрь, пока грузился октябрь, — на экране сентябрь",
      /Отметить: выплачено 5\.00 Br/.test(с.экран()) && /сентябрь 2026/.test(с.экран()), с.экран());
  }

  // ---- Текущий месяц — по часам магазина, а не телефона ----
  {
    const с = стенд(() => ответ({ period: "2026-10", current: "2026-10", open: true, pay_from: "1 ноября" }, [продавец({})]),
                    { часы: "2026-11-01T01:00:00" });      // у телефона уже ноябрь, у магазина ещё октябрь
    с.js(`payrollPeriod = "2026-10"; loadPayroll()`); await с.ждать();
    проверка("«›» закрыт: у магазина октябрь, хоть телефон и живёт в ноябре", /id="payrollNext" disabled/.test(с.экран()), с.экран());
  }

  // ---- Продавец: своя цифра словами ----
  {
    const с = стенд(() => ответ({ period: "2026-10", open: true, pay_from: "1 ноября" },
      [продавец({ carry: [{ period: "2026-08", label: "август 2026", amount: -2 }] })]), { владелец: false });
    с.js("openPayroll()"); await с.ждать();
    const э = с.экран();
    проверка("продавец, месяц идёт: «Заработано пока · месяц идёт», выплата — с 1 ноября, кнопки нет",
      /Заработано пока · месяц идёт/.test(э) && /выплата — после окончания месяца, с 1 ноября/.test(э) && !/data-pay=/.test(э), э);
    проверка("…и свой перерасчёт видит строкой", /Перерасчёт за август 2026 · учтётся при выплате/.test(э));
  }
  {
    const с = стенд(() => ответ({}, [продавец({ paid: { amount: 3, base: 5, revenue: 50, percent: 10, created_at: "2026-10-01 09:00",
      corrections: [{ period: "2026-08", label: "август 2026", amount: -2 }], now: 5, diff: 0, settled: [], left: 0 } })]), { владелец: false });
    с.js("openPayroll()"); await с.ждать();
    проверка("продавец, выплачено: «Выплачено · 01.10.2026» 3.00 и строка перерасчёта",
      /3\.00 Br<\/div><div class="statlab">Выплачено · 01\.10\.2026/.test(с.экран()) && /Перерасчёт за август 2026 — в этой выплате/.test(с.экран()), с.экран());
  }

  дошлиДоКонца = true;
  console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
  process.exit(провалов ? 1 : 0);
})();
