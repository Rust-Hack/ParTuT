// Жесты свайпом — настоящий код из 01-core.js в песочнице Node, с подменой
// экрана. Свайп, начатый на ленте, которая листается вбок (ряды фильтров,
// галерея фото, чипы каталога, карусель корзины), — это её прокрутка, а не
// «Назад» и не смена вкладки. Раньше, листая фильтры «Цен и остатков» слева
// направо, человек вылетал в «Управление», а листая фото товара назад — из
// карточки.
//
// Плюс сверка: каждая лента со стилем overflow-x: auto/scroll в styles.css
// должна быть в списке ЛЕНТЫ_ВБОК — иначе новая лента снова будет закрывать
// экран, и заметят это только на телефоне.
//
// Запуск: node tests/js/swipe_rails.cjs — печатает ✅/❌, код выхода 1 при ❌.
// Из pytest его зовёт tests/test_js_handlers.py.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const корень = path.join(__dirname, "..", "..", "partut", "webapp");
const исходник = fs.readFileSync(path.join(корень, "app", "01-core.js"), "utf8");
const начало = исходник.indexOf("// ---------- Жесты ----------");
const конец = исходник.indexOf("// ---------- Нативная кнопка «Назад» Telegram ----------");
if (начало < 0 || конец < 0) { console.log("❌ не нашёл код жестов в 01-core.js"); process.exit(1); }
const код = исходник.slice(начало, конец);

let провалов = 0, дошлиДоКонца = false;
process.on("exit", () => {
  if (!дошлиДоКонца) { console.log("❌ проверки не дошли до конца — что-то упало"); process.exitCode = 1; }
});
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}

// Элемент-заглушка: слушатели касаний, стиль, ширина.
function элемент(id, свойства = {}) {
  const слушатели = {};
  return {
    id, style: {}, clientWidth: 390, ...свойства,
    addEventListener: (тип, f) => { (слушатели[тип] = слушатели[тип] || []).push(f); },
    послать: (тип, событие) => (слушатели[тип] || []).forEach(f => f(событие)),
  };
}
// Цель касания: лежит ли она внутри ленты с таким классом (или ни в какой).
const цель = (класс) => ({
  closest: (селектор) => (класс && селектор.split(",").map(s => s.trim()).includes(класс) ? {} : null),
});

function стенд() {
  const нажато = { назад: 0, карточка: 0 };
  const кнопкаНазад = { click: () => нажато.назад++ };
  const экран = элемент("productsView", { querySelector: (s) => (s === ".viewhead button" ? кнопкаНазад : null) });
  const карточка = элемент("productView", { querySelector: () => null });
  const каталог = элемент("content");
  const вкладки = [];
  const ctx = vm.createContext({
    $: (id) => (id === "productView" ? карточка : id === "prodBack" ? { click: () => нажато.карточка++ } : null),
    document: {
      querySelectorAll: (s) => (s === ".view" ? [экран, карточка] : []),
      querySelector: (s) => (s === ".content" ? каталог : null),
      createElement: () => ({ style: {} }), body: { appendChild() {} },
    },
    NAV: [{ id: "catalog" }, { id: "fav" }, { id: "cart" }], activeTab: "fav",
    showTab: (id) => вкладки.push(id),
    setTimeout: (f) => f(), Date,
  });
  vm.runInContext(код, ctx);
  // Палец: касание в (x, 300), движение по шагам до (x + dx, 300), отпускание.
  const свайп = (эл, класс, x, dx) => {
    const t = цель(класс);
    эл.послать("touchstart", { touches: [{ clientX: x, clientY: 300 }], target: t });
    let отменено = 0;
    for (let i = 1; i <= 10; i++) {
      эл.послать("touchmove", { touches: [{ clientX: x + dx * i / 10, clientY: 300 + i * 0.3 }], target: t,
                               preventDefault() { отменено++; } });
    }
    // Что было посреди жеста: экран ехал за пальцем и забирал ли он жест у
    // прокрутки ленты (preventDefault) — после отпускания этого уже не видно.
    const посреди = { сдвиг: эл.style.transform || "", отменено };
    эл.послать("touchend", { changedTouches: [{ clientX: x + dx, clientY: 303 }], target: t });
    return посреди;
  };
  return { экран, карточка, каталог, нажато, вкладки, свайп, js: (с) => vm.runInContext(с, ctx) };
}

// ---------- Экраны управления: ряды фильтров ----------
{
  const с = стенд();
  const посреди = с.свайп(с.экран, ".chiprow", 40, 260);
  проверка("ряд фильтров: свайп слева направо — экран не закрыт", с.нажато.назад === 0, с.нажато);
  проверка("ряд фильтров: посреди жеста экран не едет и не отнимает прокрутку у ряда",
    !посреди.сдвиг && посреди.отменено === 0, посреди);
  const вне = с.свайп(с.экран, null, 40, 260);
  проверка("свайп вправо вне лент — «Назад» по-прежнему работает", с.нажато.назад === 1 && /translateX/.test(вне.сдвиг), { нажато: с.нажато, вне });
}

// ---------- Карточка товара: галерея фото ----------
{
  const с = стенд();
  с.свайп(с.карточка, ".pgal", 40, 260);
  проверка("галерея: листать фото назад — карточка не закрыта", с.нажато.карточка === 0, с.нажато);
  с.свайп(с.карточка, null, 40, 260);
  проверка("свайп вправо по карточке вне галереи — карточка закрыта", с.нажато.карточка === 1, с.нажато);
}

// ---------- Каталог: смена вкладок ----------
{
  const с = стенд();
  с.свайп(с.каталог, ".chips", 300, -200);
  с.свайп(с.каталог, ".upsell", 300, -200);
  проверка("чипы каталога и карусель корзины вкладку не меняют", с.вкладки.length === 0, с.вкладки);
  с.свайп(с.каталог, null, 300, -200);
  проверка("свайп по каталогу вне лент — следующая вкладка", с.вкладки.join() === "cart", с.вкладки);
}

// ---------- Список лент совпадает со стилями и разметкой ----------
// Лента вбок — всё, что прокручивается по горизонтали: overflow-x: auto|scroll
// или overflow, первое значение которого auto|scroll (overflow: auto — обе
// оси). Ищем в styles.css и в стилях, вписанных прямо в разметку и в код: у
// ленты без класса из списка жест «Назад» снова отнимет её прокрутку.
{
  const с = стенд();
  const ленты = new Set(с.js("ЛЕНТЫ_ВБОК").split(",").map(s => s.trim()));
  const вбок = (тело) => /overflow-x\s*:\s*(auto|scroll)/i.test(тело)
    || /(^|[;{\s"'`])overflow\s*:\s*(auto|scroll)\b/i.test(тело);
  const стили = fs.readFileSync(path.join(корень, "styles.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const найдено = [];
  for (const [, селекторы, тело] of стили.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!вбок(тело)) continue;
    селекторы.split(",").map(s => s.trim()).forEach(s => найдено.push(s));
  }
  проверка("в стилях нашлись ленты вбок (сверка не пустая)", найдено.length >= 4, найдено);
  const забыты = найдено.filter(s => !ленты.has(s));
  проверка("каждая лента вбок из стилей — в списке ЛЕНТЫ_ВБОК", !забыты.length, забыты);

  // Стиль, вписанный прямо в разметку или в код, классом не проверить —
  // лента должна получать прокрутку только классом из списка.
  const разметка = fs.readFileSync(path.join(корень, "index.html"), "utf8");
  const код = fs.readdirSync(path.join(корень, "app")).filter(f => f.endsWith(".js")).sort()
    .map(f => fs.readFileSync(path.join(корень, "app", f), "utf8")).join("\n");
  const вписанные = [...(разметка + код).matchAll(/style\s*=\s*(["'`])((?:(?!\1).)*)\1/g)].map(m => m[2]).filter(вбок);
  const присвоенные = [...код.matchAll(/\.style\.overflow(X)?\s*=\s*["'`](auto|scroll)/g)].map(m => m[0]);
  проверка("прокрутки вбок, вписанной прямо в разметку или код, нет — только классом из списка",
    !вписанные.length && !присвоенные.length, [...вписанные, ...присвоенные]);
}

дошлиДоКонца = true;
console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
process.exit(провалов ? 1 : 0);
