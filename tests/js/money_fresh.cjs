// Покупатель держит приложение открытым, продавец выдаёт заказ — на счёт
// приходит кэшбэк. Раньше профиль, бонусы и корзина показывали баланс с
// первой загрузки (0), пока приложение не перезапустят. Теперь при входе в
// эти вкладки и при возвращении в приложение баланс и колесо перечитываются,
// если показанному больше 20 секунд; сбой не превращает баланс в ноль; игру
// посреди прокрута не перерисовываем.
//
// Запуск: node tests/js/money_fresh.cjs — печатает ✅/❌, код выхода 1 при ❌.
// Из pytest его зовёт tests/test_js_handlers.py.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const текст = fs.readFileSync(path.join(__dirname, "..", "..", "partut", "webapp", "app", "01-core.js"), "utf8");
function кусок(от, до) {
  const а = текст.indexOf(от), б = текст.indexOf(до, а);
  if (а < 0 || б < 0) { console.log(`❌ не нашёл кусок: ${от}`); process.exit(1); }
  return текст.slice(а, б);
}
const деньги = кусок("let bonus = {", "async function fetchSlot()");
const вкладки = кусок("function showTab(id) {", "// ---------- Жесты");
const возврат = кусок('document.addEventListener("visibilitychange"', "let таймерПаузы");

let провалов = 0, дошлиДоКонца = false;
process.on("exit", () => {
  if (!дошлиДоКонца) { console.log("❌ проверки не дошли до конца — что-то упало"); process.exitCode = 1; }
});
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}

function стенд() {
  const сервер = { монет: 0, прокрутов: 0, лежит: false };
  const часы = { t: 1_000_000 };
  const журнал = { запросов: { bonus: 0, wheel: 0 }, профиль: 0, бонусы: 0, корзина: 0 };
  const слушатели = {};
  const документ = {
    visibilityState: "visible",
    addEventListener: (имя, f) => { слушатели[имя] = f; },
    querySelectorAll: () => [],
  };
  const вкладка = { classList: { add() {}, remove() {} } };
  const ctx = vm.createContext({
    Date: { now: () => часы.t }, JSON, Promise, Math, String, Object, initData: "qa",
    localStorage: { getItem: () => null, setItem() {} }, parseInt,
    document: документ, window: { scrollTo() {} }, $: () => вкладка,
    NAV: [{ id: "catalog" }, { id: "bonus" }, { id: "cart" }, { id: "profile" }],
    activeTab: "catalog", city: null, паузаТочки: () => null, перечитатьТочки() {}, renderNav() {}, renderFav() {},
    renderProfile: () => журнал.профиль++, renderBonus: () => журнал.бонусы++, renderCart: () => журнал.корзина++,
    slotSpinning: false, spinning: false,
    fetch: async (url) => {
      const что = url.includes("bonus") ? "bonus" : "wheel";
      журнал.запросов[что]++;
      if (сервер.лежит) throw new TypeError("Failed to fetch");
      const ответ = что === "bonus" ? { ok: true, coins: сервер.монет } : { ok: true, spins: сервер.прокрутов, progress: 0 };
      return { json: async () => ответ };
    },
  });
  vm.runInContext(деньги + "\n" + вкладки + "\n" + возврат, ctx);
  const js = (к) => vm.runInContext(к, ctx);
  const тик = async () => { for (let i = 0; i < 5; i++) await new Promise(r => setImmediate(r)); };
  return { ctx, js, сервер, часы, журнал, тик, вернуться: () => слушатели.visibilitychange() };
}

(async () => {
  const с = стенд();
  // Запуск: баланс и колесо прогреты, как prefetchBonuses() в start().
  await с.js("Promise.all([fetchBonus(), fetchWheel()])");
  проверка("при запуске баланс 0, прокрутов 0", с.js("bonus.coins") === 0 && с.js("wheel.spins") === 0);

  // Продавец выдал заказ — на сервере кэшбэк и прокрут.
  с.сервер.монет = 30; с.сервер.прокрутов = 1;

  с.часы.t += 5000;
  с.js('showTab("profile")'); await с.тик();
  проверка("через 5 с после загрузки «Профиль» не дёргает сервер — показанное свежее",
    с.журнал.запросов.bonus === 1 && с.js("bonus.coins") === 0, с.журнал.запросов);

  с.часы.t += 20000;
  const профилей = с.журнал.профиль;
  с.js('showTab("cart")'); await с.тик();
  проверка("через 25 с вход в «Корзину» перечитал баланс и колесо: 30 монет, 1 прокрут",
    с.js("bonus.coins") === 30 && с.js("wheel.spins") === 1 && с.журнал.запросов.bonus === 2, с.журнал.запросов);
  проверка("…и корзина перерисована с новым балансом (монеты можно списать)", с.журнал.корзина === 2, с.журнал);
  проверка("…профиль не трогали — он не открыт", с.журнал.профиль === профилей);

  // Двойной вход подряд — один запрос.
  с.часы.t += 30000;
  const было = с.журнал.запросов.bonus;
  с.js("освежитьДеньги(); освежитьДеньги();"); await с.тик();
  проверка("два вызова подряд — один запрос", с.журнал.запросов.bonus === было + 1, с.журнал.запросов);

  // Сеть упала — баланс не превращается в ноль.
  с.сервер.лежит = true;
  с.часы.t += 30000;
  с.js('showTab("profile")'); await с.тик();
  проверка("сеть упала — баланс остался последним известным (30), а не 0",
    с.js("bonus.coins") === 30 && с.js("bonusReady") === true);
  с.сервер.лежит = false;

  // Вернулись в приложение на «Каталоге» — пометка «перечитать», без запроса.
  с.сервер.монет = 45;
  с.часы.t += 1000;
  с.js('activeTab = "catalog"');
  const доВозврата = с.журнал.запросов.bonus;
  с.вернуться(); await с.тик();
  проверка("вернулись в приложение на «Каталоге» — сервер не дёргали", с.журнал.запросов.bonus === доВозврата);
  с.js('showTab("bonus")'); await с.тик();
  проверка("…а первый же вход в «Бонусы» перечитал: 45 — хотя прошло всего 1 с",
    с.js("bonus.coins") === 45 && с.журнал.запросов.bonus === доВозврата + 1, { монет: с.js("bonus.coins"), запросов: с.журнал.запросов });

  // Вернулись в приложение прямо на «Профиле» — перечитать сразу.
  с.сервер.монет = 50;
  с.часы.t += 1000;
  с.js('activeTab = "profile"');
  const профиль = с.журнал.профиль;
  с.вернуться(); await с.тик();
  проверка("вернулись на «Профиль» — перечитано сразу и профиль перерисован",
    с.js("bonus.coins") === 50 && с.журнал.профиль === профиль + 1, { монет: с.js("bonus.coins"), профиль: с.журнал.профиль });

  // Колесо крутится — «Бонусы» не перерисовываем, оборвали бы анимацию.
  с.сервер.монет = 60;
  с.js('activeTab = "bonus"; spinning = true');
  const бонусов = с.журнал.бонусы;
  с.js("освежитьДеньги(true)"); await с.тик();
  проверка("колесо крутится — баланс обновлён (60), а экран игры не перерисован посреди прокрута",
    с.js("bonus.coins") === 60 && с.журнал.бонусы === бонусов);
  с.js("spinning = false; slotSpinning = true");
  с.сервер.монет = 70;
  с.js("освежитьДеньги(true)"); await с.тик();
  проверка("и слот крутится — тоже не перерисовываем", с.js("bonus.coins") === 70 && с.журнал.бонусы === бонусов);

  // Ничего не поменялось — ничего не перерисовываем.
  с.js('activeTab = "cart"; slotSpinning = false');
  const корзин = с.журнал.корзина;
  с.js("освежитьДеньги(true)"); await с.тик();
  проверка("баланс прежний — корзину не перерисовываем зря", с.журнал.корзина === корзин);

  дошлиДоКонца = true;
  console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
  process.exit(провалов ? 1 : 0);
})();
