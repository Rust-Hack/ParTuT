// ручная — ответы сети отдаёт сам тест (с.ответить), в любом порядке.
function стенд({ ручная = false } = {}) {
  const сервер = { монет: 0, прокрутов: 0, лежит: false };
  const ждут = [];
  const часы = { t: 1_000_000 };
  const журнал = { запросов: { bonus: 0, wheel: 0 }, профиль: 0, бонусы: 0, корзина: 0 };
  const слушатели = {};
  const документ = {
    visibilityState: "visible",
    addEventListener: (имя, f) => { слушатели[имя] = f; },
    querySelectorAll: () => [],
  };
  const вкладка = { classList: { add() {}, remove() {} } };
  const ctx = vm.createContext({
    Date: { now: () => часы.t }, JSON, Promise, Math, String, Object, initData: "qa",
    localStorage: { getItem: () => null, setItem() {} }, parseInt,
    document: документ, window: { scrollTo() {} }, $: () => вкладка,
    NAV: [{ id: "catalog" }, { id: "bonus" }, { id: "cart" }, { id: "profile" }],
    activeTab: "catalog", city: null, паузаТочки: () => null, перечитатьТочки() {}, renderNav() {}, renderFav() {},
    renderProfile: () => журнал.профиль++, renderBonus: () => журнал.бонусы++, renderCart: () => журнал.корзина++,
    slotSpinning: false, spinning: false,
    fetch: async (url) => {
      const что = url.includes("bonus") ? "bonus" : "wheel";
      журнал.запросов[что]++;
      if (ручная) return new Promise((готов) => ждут.push({ что, готов }));
      if (сервер.лежит) throw new TypeError("Failed to fetch");
      const ответ = что === "bonus" ? { ok: true, coins: сервер.монет } : { ok: true, spins: сервер.прокрутов, progress: 0 };
      return { json: async () => ответ };
    },
  });
  vm.runInContext(деньги + "\n" + вкладки + "\n" + возврат, ctx);
  const js = (к) => vm.runInContext(к, ctx);
  const тик = async () => { for (let i = 0; i < 5; i++) await new Promise(r => setImmediate(r)); };
  // Ответить на i-й ждущий запрос: тело — то, что «прочитал сервер».
  const ответить = async (i, тело) => { ждут[i].готов({ json: async () => тело }); await тик(); };
  return { ctx, js, сервер, часы, журнал, тик, ждут, ответить, вернуться: () => слушатели.visibilitychange() };
}

