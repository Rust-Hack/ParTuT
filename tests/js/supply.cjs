    б.js('выбратьТочкуПоставки("Минск")');
    проверка("после перезапуска черновик Минска на месте", б.строка(1, "Мята").qty === "10");
    б.js('выбратьТочкуПоставки("Туров")');
    проверка("у Турова — свой черновик", б.строка(4, "").qty === "2" && б.js("пЧерн.order.join()") === "4");
    const чужой = приложение({ ls, uid: 8 });
    чужой.js('выбратьТочкуПоставки("Минск")');
