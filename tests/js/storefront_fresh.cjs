// Открытая витрина подхватывает новое (приёмка ROLE-03). Настоящий код из
// 01-core.js в песочнице Node, сервер и часы — управляемые.
//
// Владелец опубликовал товар с другого телефона — покупатель в открытом
// приложении его не находил до перезагрузки страницы: переходы между
// вкладками каталог не перечитывали. Теперь — при входе в каталог и корзину,
// при поиске и возвращении в приложение, не чаще раза в 20 с; поиск, прокрутка
// и корзина остаются; поздний ответ старого запроса не затирает свежий; сбой —
// так и сказано, с «Обновить».
//
// Запуск: node tests/js/storefront_fresh.cjs — печатает ✅/❌, код выхода 1 при ❌.
// Из pytest его зовёт tests/test_js_handlers.py.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const текст = fs.readFileSync(path.join(__dirname, "..", "..", "partut", "webapp", "app", "01-core.js"), "utf8");
const а = текст.indexOf("let витринаСвежа = true;"), б = текст.indexOf("// Витрина и админка смотрят на разные списки");
if (а < 0 || б < 0) { console.log("❌ не нашёл загрузку витрины в 01-core.js"); process.exit(1); }
const код = текст.slice(а, б);

let провалов = 0, дошлиДоКонца = false;
process.on("exit", () => {
  if (!дошлиДоКонца) { console.log("❌ проверки не дошли до конца — что-то упало"); process.exitCode = 1; }
});
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}
const тик = async () => { for (let i = 0; i < 6; i++) await new Promise(r => setImmediate(r)); };

function стенд() {
  const сервер = { товары: [{ id: 1, name: "QA кабель", price: 10 }] };
  const запросы = [];
  const часы = { сейчас: 1_000_000 };
  const узлы = {};
  const $ = (id) => узлы[id] || (узлы[id] = { id, hidden: true, innerHTML: "", disabled: false, textContent: "", onclick: null });
  const журнал = { сетка: [], корзина: 0, прокрутка: [] };
  const ctx = vm.createContext({
    $, activeTab: "catalog", allProducts: [],
    Date: class extends Date { static now() { return часы.сейчас; } },
    window: { scrollY: 640, scrollTo: (x, y) => журнал.прокрутка.push(y) },
    bootFetch: () => {
      const з = { ответ: null };
      запросы.push(з);
      return new Promise((ок, нет) => { з.ответить = (тело) => ок(тело === undefined ? JSON.parse(JSON.stringify(сервер.товары)) : тело); з.оборвать = () => нет(new TypeError("Failed to fetch")); });
    },
    updateFilterBtn() {}, renderGrid: () => журнал.сетка.push(ctx.allProducts.map(p => `${p.name} ${p.price}`).join(", ")),
    renderCart: () => журнал.корзина++, renderFav() {},
  });
  vm.runInContext(код + "\nthis.__свежа = () => витринаСвежа;", ctx);
  return { ctx, сервер, запросы, часы, журнал, узлы, js: (к) => vm.runInContext(к, ctx) };
}
// Первая загрузка витрины (как loadCatalog) — успешная.
async function открыть(с) {
  const з = с.js("fetchProducts()"); с.запросы[0].ответить(); await з;
}

(async () => {
  {
    const с = стенд();
    await открыть(с);
    с.часы.сейчас += 10_000;                                      // прошло 10 с
    await с.js("освежитьВитрину()");
    проверка("через 10 с после загрузки — каталог не перечитывается (не чаще раза в 20 с)", с.запросы.length === 1, с.запросы.length);
    с.сервер.товары.push({ id: 2, name: "QA Чехол PRO", price: 27 });   // владелец опубликовал с другого телефона
    с.часы.сейчас += 15_000;                                      // ещё 15 с — всего 25
    const з = с.js("освежитьВитрину()");
    проверка("через 25 с — перечитывает", с.запросы.length === 2, с.запросы.length);
    с.запросы[1].ответить(); await з; await тик();
    проверка("ROLE-03: новый товар виден без перезагрузки страницы — «QA Чехол PRO 27»",
      /QA Чехол PRO 27/.test(с.журнал.сетка.at(-1) || ""), с.журнал.сетка);
    проверка("…и прокрутка каталога возвращена на место (640)", с.журнал.прокрутка.at(-1) === 640, с.журнал.прокрутка);
    проверка("предупреждения «не обновилась» нет", с.узлы.catStale ? с.узлы.catStale.hidden === true : true);
  }
  {
    const с = стенд();
    await открыть(с);
    с.часы.сейчас += 30_000;
    const п1 = с.js("освежитьВитрину()"), п2 = с.js("освежитьВитрину()");
    проверка("два входа подряд, пока запрос в пути, — один запрос, а не два", с.запросы.length === 2, с.запросы.length);
    с.запросы[1].ответить(); await Promise.all([п1, п2]);
  }
  {
    // Поздний ответ старого запроса не затирает свежий.
    const с = стенд();
    await открыть(с);
    const старый = с.js("fetchProducts()");                       // например, правка в управлении
    с.сервер.товары = [{ id: 1, name: "QA кабель", price: 12 }];
    const новый = с.js("fetchProducts()");
    с.запросы[2].ответить();                                     // новый (12 Br) пришёл первым
    с.запросы[1].ответить([{ id: 1, name: "QA кабель", price: 10 }]);   // старый (10 Br) — позже
    await Promise.all([старый, новый]);
    проверка("старый ответ пришёл позже — на витрине свежая цена 12, а не 10", с.js("allProducts[0].price") === 12, с.js("allProducts[0].price"));
  }
  {
    // Сбой обновления: прежняя витрина остаётся, сказано время, «Обновить» работает.
    const с = стенд();
    await открыть(с);
    с.часы.сейчас += 30_000;
    const з = с.js("освежитьВитрину()"); с.запросы[1].оборвать(); await з;
    проверка("сбой — прежняя витрина на месте (корзина считается по ней)", с.js("allProducts.length") === 1 && с.js("__свежа()") === false);
    проверка("…и над каталогом «Не удалось обновить витрину — показана на ЧЧ:ММ» с «Обновить»",
      с.узлы.catStale && с.узлы.catStale.hidden === false && /Не удалось обновить витрину — показана на \d\d:\d\d/.test(с.узлы.catStale.innerHTML)
        && /catRetry/.test(с.узлы.catStale.innerHTML), с.узлы.catStale && с.узлы.catStale.innerHTML);
    с.узлы.catRetry.onclick();                                   // «Обновить» — сразу, без ожидания 20 с
    проверка("«Обновить» перечитывает сразу", с.запросы.length === 3, с.запросы.length);
    с.запросы[2].ответить(); await тик(); await тик();
    проверка("…удалось — предупреждение убрано", с.узлы.catStale.hidden === true && с.js("__свежа()") === true);
  }
  {
    // В корзине — перерисовывается корзина (цены и наличие), не каталог.
    const с = стенд();
    await открыть(с);
    с.ctx.activeTab = "cart";
    с.часы.сейчас += 30_000;
    const з = с.js("освежитьВитрину()"); с.запросы[1].ответить(); await з;
    проверка("в корзине — перерисована корзина, не каталог", с.журнал.корзина === 1 && с.журнал.сетка.length === 0, с.журнал);
  }

  дошлиДоКонца = true;
  console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
  process.exit(провалов ? 1 : 0);
})();
