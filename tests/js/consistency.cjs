// Единообразие мелочей (В-5, проход трёх ролей 6.10) — настоящий код и
// разметка приложения:
//   а) деньги в полях карточки товара — с копейками («18.50», а не «18.5»), как
//      в списках («18.50 Br»); подпись «Уже на точках» — тоже;
//   б) кнопка в шапке экрана везде «‹ Назад» — «Закрыть» было у трёх экранов;
//   в) точка, уже выбранная в другом блоке мастера, выглядит недоступной;
//   г) вводный текст журнала говорит, что в нём видно, а не историю разработки.
// Подсказка у занятой точки (в) проверяется в new_product.cjs, режим «Убрать
// вкусы…» (В-3) — в card_unsaved.cjs.
//
// Запуск: node tests/js/consistency.cjs — печатает ✅/❌, код выхода 1 при ❌.
// Из pytest его зовёт tests/test_js_handlers.py.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const корень = path.join(__dirname, "..", "..", "partut", "webapp");
const читать = (имя) => fs.readFileSync(path.join(корень, имя), "utf8");
const каталог = читать("app/06-catalog.js"), админка = читать("app/04-admin.js");
const разметка = читать("index.html"), стили = читать("styles.css");

let провалов = 0, дошлиДоКонца = false;
process.on("exit", () => {
  if (!дошлиДоКонца) { console.log("❌ проверки не дошли до конца — что-то упало"); process.exitCode = 1; }
});
function проверка(что, ок, подробно) {
  if (!ок) провалов++;
  console.log((ок ? "✅ " : "❌ ") + что + (ок || подробно === undefined ? "" : " — " + JSON.stringify(подробно)));
}

// ---- а) деньги в полях ----
{
  const а = каталог.indexOf("function деньгиВПоле(x)"), б = каталог.indexOf("\n}\n", а);
  проверка("а) в 06-catalog.js есть деньгиВПоле", а >= 0 && б > а);
  const ctx = vm.createContext({ String, Number });
  vm.runInContext(а >= 0 ? каталог.slice(а, б + 2) : "function деньгиВПоле() {}", ctx);
  const в = (x) => vm.runInContext(`деньгиВПоле(${JSON.stringify(x)})`, ctx);
  const пары = [[18.5, "18.50"], ["18,5", "18.50"], [25, "25.00"], ["7.1", "7.10"], [0, "0.00"], ["", ""], [null, ""], ["abc", "abc"]];
  const не = пары.filter(([x, ждём]) => в(x) !== ждём).map(([x, ждём]) => [x, ждём, в(x)]);
  проверка("а) 18.5 → «18.50», «18,5» → «18.50», 25 → «25.00», пусто — пусто, не число — как ввели", !не.length, не);
  проверка("а) поля цены и закупки карточки заполняются через деньгиВПоле — ни одного голого ${p.price}",
    !/value="\$\{p\.price\}"/.test(каталог) && (каталог.match(/value="\$\{деньгиВПоле\(p\.price\)\}"/g) || []).length === 4
    && (каталог.match(/value="\$\{p\.cost \? деньгиВПоле\(p\.cost\) : ""\}"/g) || []).length === 4);
  проверка("а) снимок закупки «как было» — в том же виде, что поле (сравнение строкой)",
    /editOrigCost = p\.cost \? деньгиВПоле\(p\.cost\) : ""/.test(каталог));
  проверка("а) «Уже на точках: Минск — 18.50 Br» — с копейками",
    /`\$\{esc\(p\.city\)\} — \$\{Number\(p\.price\)\.toFixed\(2\)\} Br, \$\{p\.stock\} шт`/.test(админка));
}

// ---- б) кнопка в шапке экрана ----
{
  // Каждая шапка — со своим экраном (ближайший открывающий тег экрана выше).
  // У части экранов класс «view ontop», поэтому класс — по началу, а не целиком.
  const шапки = [];
  const re = /<div class="view[^"]*"[^>]*id="([^"]+)"|<div class="viewhead">([\s\S]*?)<\/div>/g;
  let экран = "?", m;
  while ((m = re.exec(разметка))) {
    if (m[1]) { экран = m[1]; continue; }
    шапки.push({ экран, кнопка: ((m[2].match(/<button class="closebtn"[^>]*>([^<]*)<\/button>/) || [])[1] || "").trim() });
  }
  const всего = (разметка.match(/class="viewhead"/g) || []).length;
  const иначе = шапки.filter(x => x.кнопка !== "‹ Назад");
  проверка(`б) шапок экранов ${всего}, все разобраны, кнопка везде «‹ Назад»`,
    всего > 0 && шапки.length === всего && !иначе.length, иначе);
  проверка("б) в том числе «Управление», карточка товара и «Заказы»",
    ["adminView", "editView", "ordersView"].every(id => (шапки.find(x => x.экран === id) || {}).кнопка === "‹ Назад"));
}

// ---- в) недоступная точка в мастере ----
проверка("в) .ochip:disabled — приглушена, как недоступные кнопки других видов",
  /\.ochip:disabled \{ opacity: \.45; cursor: default; \}/.test(стили));

// ---- г) вводный текст журнала ----
{
  const ТЕКСТ = "Кто, когда и что менял в магазине: цены, остатки, товары, заказы, настройки. Продавцы здесь видят только свои действия.";
  проверка("г) у владельца — что в журнале видно, и одинаково в разметке и в коде",
    разметка.includes(ТЕКСТ) && админка.includes(ТЕКСТ));
  проверка("г) без истории разработки («раньше писался», «прежде менялось бесследно»)",
    !/раньше писался|прежде менялось бесследно/.test(разметка + админка));
}

дошлиДоКонца = true;
console.log(провалов ? `\nНе прошло: ${провалов}` : "\nВсё прошло");
process.exit(провалов ? 1 : 0);
