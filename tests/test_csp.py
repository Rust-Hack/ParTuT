"""Политика безопасности страницы (CSP) пускает всё, чем страница сама
показывает картинки, — и ничего чужого.

1 октября 2026 выяснилось: превью только что выбранного фото — в карточке
товара, в форме модели — с 20 августа было битой картинкой. Превью делается
через URL.createObjectURL (адрес вида blob:…), а политика, введённая
20 августа, разрешала картинки только со своего адреса и data:. Браузер
молча отказывал, а фото после сохранения показывалось как надо — поэтому
шесть недель этого никто не видел.

Здесь связь проверяется без браузера: если код приложения создаёт
blob-адреса, политика обязана их пускать. И обратное: в img-src и script-src
нет лишних чужих адресов — ослабить политику «заодно» не выйдет незаметно.
"""
import os
import re

from _common import Checker, client

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПРИЛОЖЕНИЕ = os.path.join(КОРЕНЬ, "partut", "webapp", "app")


def _правила(заголовок):
    правила = {}
    for часть in заголовок.split(";"):
        слова = часть.split()
        if слова:
            правила[слова[0]] = слова[1:]
    return правила


def run():
    c = Checker("Политика безопасности страницы (CSP)")
    ответ = client.get("/")
    заголовок = ответ.headers.get("Content-Security-Policy", "")
    c("у страницы приложения есть политика", bool(заголовок))
    правила = _правила(заголовок)

    код = ""
    for имя in sorted(os.listdir(ПРИЛОЖЕНИЕ)):
        if имя.endswith(".js"):
            with open(os.path.join(ПРИЛОЖЕНИЕ, имя), encoding="utf-8") as f:
                код += f.read()

    картинки = правила.get("img-src", [])
    if "URL.createObjectURL(" in код:
        c("код делает превью через blob: — политика их пускает (иначе превью — битая картинка)",
          "blob:" in картинки)
    if re.search(r"data:image/", код):
        c("код показывает картинки data: — политика их пускает", "data:" in картинки)
    чужие = [x for x in картинки if x not in ("'self'", "data:", "blob:")]
    c("картинки — только свои: ни одного чужого адреса" + (f": {чужие}" if чужие else ""), not чужие)
    скрипты = правила.get("script-src", [])
    c("скрипты — только свои и Телеграма",
      sorted(скрипты) == sorted(["'self'", "'unsafe-inline'", "https://telegram.org"]))
    c("подключения — только к своему серверу", правила.get("connect-src") == ["'self'"])
    return c.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
