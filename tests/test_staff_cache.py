"""Кэш прав продавцов: опоздавшее чтение не затирает свежий список (3.10.2026).

Права держатся в памяти 30 секунд (config._staff_by_city). Чтение базы,
начатое ДО того, как владелец добавил продавца, заканчивалось ПОСЛЕ сброса
кэша (refresh_staff) — и клало в кэш старый список со свежей отметкой
времени. Новый продавец полминуты получал отказ. Поймано на полном прогоне
тестов: 7302 продавец, а 7303, добавленный следующей строкой, — «покупатель».

Здесь гонка воспроизводится нарочно: читатель базы ждёт, пока продавца
добавят и кэш сбросят, и только потом отдаёт прочитанное раньше.
"""
import threading

from _common import db, Checker

from partut import config

НОВЫЙ = 7391


def run():
    c = Checker("Кэш прав продавцов")
    настоящий = config._читатель_продавцов
    прочитал, можно_отдать = threading.Event(), threading.Event()
    старый = {k: set(v) for k, v in настоящий().items()}      # список ДО добавления

    def медленный():
        прочитал.set()
        можно_отдать.wait(5)
        return старый

    try:
        config.refresh_staff()
        config.set_staff_source(медленный)
        поток = threading.Thread(target=config.is_admin, args=(НОВЫЙ,))
        поток.start()                                         # чтение началось ДО добавления
        прочитал.wait(5)
        config.set_staff_source(настоящий)
        db.add_staff(НОВЫЙ, "", "продавец из гонки")         # владелец добавил продавца…
        config.refresh_staff()                                # …и кэш сброшен
        можно_отдать.set()                                    # опоздавшее чтение вернулось
        поток.join(5)
        c("опоздавшее чтение не вернуло старый список: новый продавец сразу продавец",
          config.admin_role(НОВЫЙ) == "seller")
        db.remove_staff(НОВЫЙ)
        config.refresh_staff()
        c("снятый продавец сразу без доступа", config.admin_role(НОВЫЙ) == "")
    finally:
        config.set_staff_source(настоящий)
        можно_отдать.set()
        config.refresh_staff()
    return c.fails
