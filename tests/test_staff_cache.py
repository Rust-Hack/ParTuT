"""Кэш прав продавцов: опоздавшее чтение не затирает свежий список (3.10.2026).

Права держатся в памяти 30 секунд (config._staff_by_city). Чтение базы,
начатое ДО того, как владелец добавил продавца, заканчивалось ПОСЛЕ сброса
кэша (refresh_staff) — и клало в кэш старый список со свежей отметкой
времени. Новый продавец полминуты получал отказ. Поймано на полном прогоне
тестов: 7302 продавец, а 7303, добавленный следующей строкой, — «покупатель».

Здесь гонка воспроизводится нарочно: читатель базы ждёт, пока продавца
добавят и кэш сбросят, и только потом отдаёт прочитанное раньше.

Второе (8.10.2026, нагрузка на копии): одно НЕУДАЧНОЕ чтение ложилось в кэш
пустым списком на полминуты. Все продавцы получали «нет доступа», а заказы
их точек уходили уведомлением владельцу — даже когда база уже ожила.
"""
import threading
import time

from _common import db, Checker

from partut import config

НОВЫЙ = 7391
СБОЙ_ПРОДАВЕЦ, СБОЙ_НОВЫЙ = 7392, 7393


def run():
    c = Checker("Кэш прав продавцов")
    настоящий = config._читатель_продавцов
    прочитал, можно_отдать = threading.Event(), threading.Event()
    старый = {k: set(v) for k, v in настоящий().items()}      # список ДО добавления

    def медленный():
        прочитал.set()
        можно_отдать.wait(5)
        return старый

    try:
        config.refresh_staff()
        config.set_staff_source(медленный)
        поток = threading.Thread(target=config.is_admin, args=(НОВЫЙ,))
        поток.start()                                         # чтение началось ДО добавления
        прочитал.wait(5)
        config.set_staff_source(настоящий)
        db.add_staff(НОВЫЙ, "", "продавец из гонки")         # владелец добавил продавца…
        config.refresh_staff()                                # …и кэш сброшен
        можно_отдать.set()                                    # опоздавшее чтение вернулось
        поток.join(5)
        c("опоздавшее чтение не вернуло старый список: новый продавец сразу продавец",
          config.admin_role(НОВЫЙ) == "seller")
        db.remove_staff(НОВЫЙ)
        config.refresh_staff()
        c("снятый продавец сразу без доступа", config.admin_role(НОВЫЙ) == "")
    finally:
        config.set_staff_source(настоящий)
        можно_отдать.set()
        config.refresh_staff()
    return c.fails


def run_сбой_чтения():
    c = Checker("Кэш прав продавцов: сбой чтения — не «продавцов нет»")
    настоящий = config._читатель_продавцов
    состав = {"Минск": {СБОЙ_ПРОДАВЕЦ}}
    сломано = {"да": False}

    def читатель():
        if сломано["да"]:
            raise RuntimeError("connection to server failed: Can't assign requested address")
        return {город: set(ids) for город, ids in состав.items()}

    def устарел():
        with config._staff_lock:
            config._staff_cache["at"] = time.time() - config._STAFF_TTL - 1

    config.set_staff_source(читатель)
    config.refresh_staff()
    try:
        c("база отвечает — продавец с доступом", config.is_admin(СБОЙ_ПРОДАВЕЦ))
        устарел(); сломано["да"] = True
        c("кэш устарел, база не ответила — доступ остаётся (последний прочитанный список)",
          config.is_admin(СБОЙ_ПРОДАВЕЦ))
        c("…и заказ Минска уходит продавцу Минска, а не владельцу",
          config.admins_for_city("Минск") == {СБОЙ_ПРОДАВЕЦ})

        # База ожила, а состав за это время поменяли в ней напрямую: первый же
        # запрос читает базу, а не держит сбой полминуты.
        сломано["да"] = False
        состав["Минск"] = {СБОЙ_ПРОДАВЕЦ, СБОЙ_НОВЫЙ}
        c("база ожила — первый же запрос читает её снова", config.is_admin(СБОЙ_НОВЫЙ))

        # Состав меняли через приложение (refresh_staff), и тут база молчит:
        # прежний список уже неверен — продавцы ждут базу, владелец при деле.
        config.refresh_staff(); сломано["да"] = True
        c("после смены состава при молчащей базе старому списку не верим",
          not config.is_admin(СБОЙ_ПРОДАВЕЦ) and not config.is_admin(СБОЙ_НОВЫЙ))
        c("…заказ при этом не теряется — уходит владельцу",
          config.admins_for_city("Минск") == set(config.SUPER_ADMIN_IDS))
    finally:
        config.set_staff_source(настоящий)
        config.refresh_staff()
    return c.fails
