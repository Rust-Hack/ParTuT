"""Направление зависимостей: стрелки не должны замыкаться в круг.

История простая. db.py и server.py разрезали на модули, и каждый вынесенный
кусок импортировал тот файл, из которого его вынесли, — чтобы дотянуться до
get_admin, _cache_bust или connect. А исходный файл импортировал их обратно,
внизу, «ради регистрации маршрутов». Получилось четырнадцать кругов, живых
только потому, что импорты стояли в последних строках файла.

Круг — это не стиль. Это значит, что модуль нельзя ни прочитать, ни
запустить, ни проверить отдельно: тянешь один — приезжает всё.

Со стороны сервера круги разорваны: помощники уехали в листовые модули
(auth, cache, inputs, photos, tgsend, shopinfo), а маршруты объявляются на
Blueprint и подключаются фабрикой. Ни один модуль с ручками больше не знает
про server.

Со стороны базы круги ОСТАЛИСЬ, и осознанно. Из двух сотен обращений db_* к db
185 — это примитивы (connect, _q), их можно вынести в листовой модуль. Но
оставшиеся полтора десятка — настоящие вызовы (log_coins, ensure_user), и они
круг сохранят. То есть работа убрала бы связность, но не саму беду. Поэтому
здесь стоит счётчик: меньше — хорошо, больше — нельзя.
"""
import ast
import io
import os

from _common import Checker

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАКЕТ = os.path.join(КОРЕНЬ, "partut")

# Модули, которые обязаны оставаться листьями: их импортируют все, и стоит им
# самим что-то потянуть — этот «кто-то» приедет в каждый тест и каждый скрипт.
ЛИСТЬЯ = ["partut.config", "partut.cache", "partut.inputs", "partut.paths"]

# Модули с ручками: каждый объявляет свой Blueprint, и ни один не знает про
# фабрику. Список руками — чтобы забытый при переезде модуль был виден.
РУЧЕЧНЫЕ = ["partut.web." + и for и in
            ("admin", "catalog", "customers", "games", "orders", "promos", "shop", "stock")]

ФАБРИКА = "partut.web.server"

# Круги на стороне базы приняты осознанно и имеют РОВНО одну форму: ядро базы
# подтягивает имена вынесенного куска, а кусок зовёт ядро (db.connect()). Это
# цена того, что весь магазин обращается к базе через один модуль `db`.
#
# Раньше здесь стоял счётчик «кругов не больше шести». Он врал в обе стороны:
# вынесешь ещё один кусок — счётчик краснеет на полезной работе; заведёшь
# настоящий круг между чужими модулями — а он в лимит уложится. Поэтому
# проверяем не количество, а ФОРМУ: любой круг обязан быть парой
# «ядро базы ↔ его собственный кусок», всё прочее — беда.
ЯДРО_БАЗЫ = "partut.db"


def _модули():
    """Все модули пакета плюс точка входа — по полным именам (partut.web.orders).

    Раньше здесь читался список .py из корня репозитория. После переезда в пакет
    корень опустел бы, граф вышел пустым — и тест прошёл бы ВХОЛОСТУЮ, ничего не
    проверив. Поэтому имена собираются обходом пакета, а run.py добавляется явно.
    """
    найдено = {}
    for папка, _, файлы in os.walk(ПАКЕТ):
        if "__pycache__" in папка:
            continue
        for ф in файлы:
            if not ф.endswith(".py"):
                continue
            путь = os.path.join(папка, ф)
            отн = os.path.relpath(путь, КОРЕНЬ)[:-3].replace(os.sep, ".")
            найдено[отн[:-9] if отн.endswith(".__init__") else отн] = путь
    найдено["run"] = os.path.join(КОРЕНЬ, "run.py")
    return найдено


def _граф():
    модули = _модули()
    граф = {}
    for имя, путь in sorted(модули.items()):
        куда = set()
        for n in ast.walk(ast.parse(io.open(путь, encoding="utf-8").read())):
            if isinstance(n, ast.Import):
                куда |= {a.name for a in n.names if a.name in модули}
            elif isinstance(n, ast.ImportFrom) and n.module and n.level == 0:
                # `from partut.web import auth` — стрелка к partut.web.auth, а не
                # к пакету partut.web: иначе каждый модуль «зависел» бы от папки,
                # в которой лежит, и круги считались бы на пустом месте.
                подмодули = {f"{n.module}.{a.name}" for a in n.names} & set(модули)
                куда |= подмодули or ({n.module} & set(модули))
        граф[имя] = куда - {имя}
    return граф


def _круги(граф):
    цвет, найдено = {}, []
    def обход(u, путь):
        цвет[u] = 1
        for v in sorted(граф.get(u, ())):
            if цвет.get(v) == 1:
                найдено.append(" → ".join(путь[путь.index(v):] + [v]) if v in путь
                               else " → ".join(путь + [v]))
            elif цвет.get(v, 0) == 0:
                обход(v, путь + [v])
        цвет[u] = 2
    for u in sorted(граф):
        if цвет.get(u, 0) == 0:
            обход(u, [u])
    return найдено


def run():
    граф = _граф()

    c = Checker("Листья ничего не тянут за собой")
    for лист in ЛИСТЬЯ:
        c(f"{лист} ни от кого не зависит"
          + ("" if not граф.get(лист) else f": {sorted(граф[лист])}"), not граф.get(лист))

    c2 = Checker("Модули с ручками не знают про фабрику")
    пропали = [и for и in РУЧЕЧНЫЕ if и not in граф]
    c2(f"все модули с ручками на месте{'' if not пропали else ': нет ' + str(пропали)}",
       not пропали)
    for и in РУЧЕЧНЫЕ:
        c2(f"{и} не импортирует {ФАБРИКА}", ФАБРИКА not in граф.get(и, set()))

    c3 = Checker("Стрелка от фабрики к модулям — односторонняя")
    c3("фабрика подключает все модули с ручками",
       set(РУЧЕЧНЫЕ) <= граф.get(ФАБРИКА, set()))
    # Кто вообще имеет право знать про фабрику: только точка запуска.
    знают = sorted(и for и, куда in граф.items() if ФАБРИКА in куда and и != ФАБРИКА)
    c3(f"про фабрику знает только run: {знают}", знают == ["run"])

    c4 = Checker("Круги только принятой формы")
    круги = _круги(граф)
    серверные = [к for к in круги if ".web." in к or к.startswith("partut.web")]
    c4("на стороне сайта кругов нет" + ("" if not серверные else f": {серверные}"),
       not серверные)

    def принятый(круг):
        """«partut.db → partut.db.orders → partut.db» — ядро и его же кусок."""
        участники = {ч.strip() for ч in круг.split("→")}
        прочие = участники - {ЯДРО_БАЗЫ}
        return (ЯДРО_БАЗЫ in участники and прочие
                and all(ч.startswith(ЯДРО_БАЗЫ + ".") for ч in прочие))

    чужие = [к for к in круги if not принятый(к)]
    c4("каждый круг — это ядро базы и его собственный кусок"
       + ("" if not чужие else f"; посторонние: {чужие}"), not чужие)

    # И столько же, сколько кусков: круг на каждый вынесенный модуль — ровно
    # один. Если их вдруг меньше, значит какой-то кусок ядро не зовёт и живёт
    # своей жизнью; если больше — круг завёлся не там, где мы думаем.
    куски = {и for и in граф if и.startswith(ЯДРО_БАЗЫ + ".") and ЯДРО_БАЗЫ in граф[и]}
    c4(f"кругов ровно по числу кусков базы ({len(круги)} и {len(куски)})",
       len(круги) == len(куски) and len(куски) >= 6)

    return c.fails + c2.fails + c3.fails + c4.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
