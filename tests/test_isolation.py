"""Подмена прав живёт ровно один тест.

Ради этого переезд на pytest и затевался. as_admin() подменяет auth.get_admin
насовсем — и проверка прав, написанная после него, проходила ВХОЛОСТУЮ:
посторонний оказывался админом, отказа не было, тест зеленел. Так уже было, и
поймали это случайно, а не проверкой.

Здесь два теста подряд: первый пачкает состояние, второй смотрит, убрали ли за
ним. Порядок внутри файла pytest сохраняет — он и есть суть проверки.
"""
import auth
from _common import as_admin, REAL_GET_ADMIN


def test_подмена_ставится():
    as_admin(4242)
    assert auth.get_admin("что угодно")["id"] == 4242, "подмена не сработала"


def test_после_теста_права_настоящие():
    # Если фикстура из conftest перестанет работать, здесь останется подмена
    # из предыдущего теста — и это единственное место, где такое видно.
    assert auth.get_admin is REAL_GET_ADMIN, (
        "подмена прав пережила тест — проверки прав в других файлах "
        "проходят вхолостую")
    assert auth.get_admin("мусор") is None, "посторонний не должен быть админом"
