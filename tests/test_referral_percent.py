"""Реферальные проценты: начисляются ли с КАЖДОГО заказа и растёт ли ступень.

Проверяем то, что нельзя увидеть чтением: процент считается от числа
приглашённых, которые УЖЕ покупали, и пересчитывается на каждом заказе заново.
Ошибка здесь тихая — пригласивший просто получает меньше, чем обещано на
экране, и заметит это в лучшем случае через месяц.
"""
from _common import db, client, Checker, as_admin, as_user

from partut import cache
from partut.db import customers as c_mod


ПРИГЛАСИВШИЙ = 8100


def _clean():
    conn = db.connect(); cur = conn.cursor()
    cur.execute("DELETE FROM orders")
    cur.execute("DELETE FROM products")
    cur.execute(db._q("DELETE FROM users WHERE user_id >= %s"), (8100,))
    conn.commit(); conn.close()
    cache.bust()


def _друг(uid):
    """Новый приглашённый, ещё не активный."""
    db.ensure_user(uid)
    db.set_referrer_once(uid, ПРИГЛАСИВШИЙ)
    return uid


def _покупка(uid, pid, сумма):
    """Заказ друга, доведённый до «выдан» — только он и активирует реферала."""
    oid, *_ = db.place_order(uid, f"u{uid}", "Минск",
                             [{"id": pid, "name": "Реф-под", "price": сумма, "qty": 1, "cost": 0}],
                             сумма, 0, 0.01, 0, "Самовывоз", "ул. Тест 1", "cash", "", "", "paid")
    r = client.post("/api/admin/order/status", json={"initData": "x", "id": oid, "action": "issued"})
    return oid, r


def run():
    c = Checker("Реферальные проценты")
    _clean()
    as_admin()
    db.ensure_user(ПРИГЛАСИВШИЙ)
    pid = db.add_product("Минск", "pods", "Реф-под", 100.0, 500, cost=0)

    # --- Ступени процента по числу АКТИВНЫХ (тех, кто уже купил) ---
    c("без рефералов — нижняя ступень", db.ref_percent(0) == 2)
    c("на пятом активном ступень выше", db.ref_percent(5) == 3)
    c("на десятом ещё выше", db.ref_percent(10) == 4)
    c("на пятнадцатом верхняя", db.ref_percent(15) == 5)
    c("между ступенями процент не растёт", db.ref_percent(4) == 2 and db.ref_percent(9) == 3)

    # --- Первый заказ друга: процент + разовый бонус ---
    друг1 = _друг(8101)
    было = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    _покупка(друг1, pid, 100.0)
    стало = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    бонус = db.referral_bonus()
    # 100 Br * 2% = 200 монет (1 Br = 100 монет), плюс разовый бонус.
    c("за первый заказ друга пришли процент и бонус", стало - было == 200 + бонус)
    c("друг стал активным", c_mod.count_active_referrals(ПРИГЛАСИВШИЙ) == 1)

    # --- Второй заказ ТОГО ЖЕ друга: процент есть, бонуса больше нет ---
    было = стало
    _покупка(друг1, pid, 100.0)
    стало = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    c("со второго заказа идёт только процент", стало - было == 200)

    # --- Набираем активных до следующей ступени ---
    for uid in range(8102, 8106):          # ещё четверо → всего пятеро активных
        _покупка(_друг(uid), pid, 100.0)
    c("активных стало пятеро", c_mod.count_active_referrals(ПРИГЛАСИВШИЙ) == 5)
    c("ступень поднялась", db.ref_percent(c_mod.count_active_referrals(ПРИГЛАСИВШИЙ)) == 3)

    было = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    _покупка(друг1, pid, 100.0)
    стало = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    c("новый процент применился к следующему заказу", стало - было == 300)

    # --- Приглашённый, который ещё не покупал, ступень не двигает ---
    _друг(8110)
    c("неактивный не считается", c_mod.count_active_referrals(ПРИГЛАСИВШИЙ) == 5)

    # --- Заработок копится в отдельном счётчике, он же виден в бонусах ---
    # Считаем ожидаемое по шагам, а не «больше нуля»: процент берётся ДО того,
    # как очередной друг стал активным, и именно в этом легко ошибиться.
    ожидаем = (200 + бонус)          # друг1, первый заказ: 2% + разовый бонус
    ожидаем += 200                   # друг1, второй заказ: только процент
    ожидаем += 4 * (200 + бонус)     # ещё четверо: у каждого первый заказ, всё ещё 2%
    ожидаем += 300                   # друг1 снова, активных уже пятеро — 3%
    строка = db.get_user_row(ПРИГЛАСИВШИЙ)
    c("заработок посчитан до монеты", int(строка["ref_earned"] or 0) == ожидаем)
    c("заработок не больше баланса", int(строка["ref_earned"] or 0) <= int(строка["coins"] or 0))

    # --- Доставка не входит в базу процента — та же база, что у кэшбэка ---
    # Раньше процент считался от order["total"] (товары + доставка), а кэшбэк
    # и прогресс колеса — от одних товаров. Магазин не зарабатывает на дороге,
    # платить с неё процент незачем.
    c2 = Checker("Доставка не входит в базу процента")
    друг2 = _друг(8120)
    было = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    oid, coins_used, total, _ = db.place_order(
        друг2, f"u{друг2}", "Минск",
        [{"id": pid, "name": "Реф-под", "price": 100.0, "qty": 1, "cost": 0}],
        100.0, 20.0, 0.01, 0, "Доставка", "ул. Тест 1", "cash", "", "", "paid")
    c2("заказ действительно с доставкой", total == 120.0)
    client.post("/api/admin/order/status", json={"initData": "x", "id": oid, "action": "issued"})
    стало = db.get_user_row(ПРИГЛАСИВШИЙ)["coins"] or 0
    # На этой ступени (5 активных) процент 3%: 100 Br * 3% = 300 монет, БЕЗ
    # бонуса за первого (это уже не первый друг у пригласившего, но для
    # друга2 это его собственный первый заказ — бонус будет, считаем его).
    c2("процент — от товаров (100 Br), а не от товаров+доставки (120 Br)",
       стало - было == 300 + бонус)

    # --- История начислений: видно, ЗА КАКОГО друга пришли монеты ---
    # Раньше был виден только итог (ref_earned) — разбивку по друзьям
    # восстановить было нечем: coin_log не помнил, чей это был заказ.
    c3 = Checker("История начислений по рефералам")
    db.remember_user_name(друг2, "friend_two", "Друг Второй")
    as_user(ПРИГЛАСИВШИЙ, "приглашающий")
    r = client.post("/api/referral/history", json={"initData": "x"})
    hist = (r.get_json() or {}).get("history") or []
    c3("запись про друга2 есть", any(h["friend"] == "Друг Второй" and h["delta"] == 300 for h in hist))
    c3("и бонус за его первый заказ тоже своей строкой",
       any(h["friend"] == "Друг Второй" and h["delta"] == бонус for h in hist))
    c3("новые записи сверху", bool(hist) and hist[0]["at"] >= hist[-1]["at"])
    # Друг без имени и username в Telegram — не пустая строка, а «друг».
    db.ensure_user(8130)
    db.set_referrer_once(8130, ПРИГЛАСИВШИЙ)
    as_admin()
    _покупка(8130, pid, 100.0)
    as_user(ПРИГЛАСИВШИЙ, "приглашающий")
    r = client.post("/api/referral/history", json={"initData": "x"})
    hist = (r.get_json() or {}).get("history") or []
    c3("безымянный друг подписан как «друг», не пусто", any(h["friend"] == "друг" for h in hist))
    as_admin()

    _clean()
    return c.fails + c2.fails + c3.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
