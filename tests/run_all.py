"""
Прогон всех тестов перед деплоем:  python tests/run_all.py
Код выхода 0 = всё зелёное, 1 = есть падения (не деплоить).

Внутри — pytest, и это важно. Раньше здесь был свой обход с двумя списками,
которые велись руками: имена файлов и имена дополнительных функций. Оба
неизбежно отставали от кода — так и вышло: run_model_reviews в test_reviews.py
существовала, в списке её не было, и она не запускалась НИ РАЗУ. Проверка,
которую никто не гоняет, хуже отсутствующей: она создаёт уверенность.

Двух запускателей нет намеренно. Будь их два, они однажды разошлись бы — и
снова оказалось бы, что часть проверок не гоняет никто.

Отсюда же остаётся всё привычное:
    python tests/run_all.py            весь набор, как раньше
    venv/bin/pytest tests/ --lf        только упавшие в прошлый раз
    venv/bin/pytest tests/ -k заказ    по имени
"""
import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))


def main():
    try:
        import pytest
    except ImportError:
        print("Не найден pytest. Поставьте: venv/bin/pip install -r requirements-dev.txt")
        return 1
    # -s: печать проверок (те самые ✅/❌) идёт на экран, а не в буфер pytest.
    # -q: без длинной шапки — сводка внизу и так своя.
    код = pytest.main([ЗДЕСЬ, "-s", "-q", "--no-header", "-p", "no:cacheprovider"])
    print("\n" + "=" * 40)
    if код == 0:
        print("✅ ВСЕ ТЕСТЫ ПРОШЛИ — можно деплоить")
        return 0
    print("❌ ЕСТЬ ПАДЕНИЯ — не деплоить. Подробности выше.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
