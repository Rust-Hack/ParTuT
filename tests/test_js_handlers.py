def run():
    c = Checker("Экраны: что уходит на сервер")
    node = shutil.which("node")
    c("Node установлен (без него проверки экранов не запустить)", bool(node))
    if not node:
        return c.fails
    for имя, не_меньше in СКРИПТЫ.items():
        r = subprocess.run([node, os.path.join(КОРЕНЬ, "tests", "js", имя)],
                           capture_output=True, text=True, timeout=60, cwd=КОРЕНЬ)
        вывод = r.stdout + r.stderr
        прошли = вывод.count("✅")
        for строка in вывод.splitlines():
            if строка.startswith("❌"):
                c(f"{имя}: {строка[2:].strip()}", False)
        c(f"{имя}: все проверки прошли (код выхода {r.returncode})", r.returncode == 0)
        c(f"{имя}: проверок не меньше {не_меньше} (прошло {прошли})", прошли >= не_меньше)
    return c.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
