"""Экраны приложения — что они ОТПРАВЯТ. Серверные тесты этого не видят.

Приёмка 30 сентября 2026 нашла три ошибки, которые жили только в экране
склада: пересчёт уходил, пока невыданные заказы ещё грузились (S-01); после
отказа «уже записано» следующий тап отправлял число как новый приход (S-02);
у заказа с двумя вкусами было две галочки, а в расчёт шла одна (S-03). Потом
ещё две — в быстрой цене: закрыли и открыли окно заново — и приложение
забывало, что ответ на прошлое сохранение не пришёл (B); ответ, оборванный
на середине, выдавался за «цена не сохранилась» (C).

Сами проверки — в tests/js/*.cjs: настоящий код экранов из partut/webapp/app в
песочнице Node с подменой экрана и сети. Здесь — только запуск, чтобы они
шли в общем прогоне и в CI.

Проверка, которая «прошла», потому что ничего не запустила, хуже упавшей: без
Node или с меньшим числом проверок, чем ожидается, — это провал, а не пропуск.
"""
import os
import shutil
import subprocess

from _common import Checker

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Скрипт → сколько проверок в нём сейчас. Меньше — какая-то выпала молча.
СКРИПТЫ = {
    "stock_dialog.cjs": 19,     # окно «📦 Склад»: S-01..S-03
    # быстрая цена: QP-01 (чужой ответ), QP-02 (неизвестный исход), B (сомнение
    # помнится при товаре, а не при окне), C (оборванный ответ — не «не сохранилось»)
    "quick_price.cjs": 68,
    "product_row.cjs": 30,      # строка товара: остаток словами, точка, неподтверждённая цена
    "swipe_rails.cjs": 9,       # свайп по ленте вбок — её прокрутка, а не «Назад»
}


def run():
    c = Checker("Экраны: что уходит на сервер")
    node = shutil.which("node")
    c("Node установлен (без него проверки экранов не запустить)", bool(node))
    if not node:
        return c.fails
    for имя, не_меньше in СКРИПТЫ.items():
        r = subprocess.run([node, os.path.join(КОРЕНЬ, "tests", "js", имя)],
                           capture_output=True, text=True, timeout=60, cwd=КОРЕНЬ)
        вывод = r.stdout + r.stderr
        прошли = вывод.count("✅")
        for строка in вывод.splitlines():
            if строка.startswith("❌"):
                c(f"{имя}: {строка[2:].strip()}", False)
        c(f"{имя}: все проверки прошли (код выхода {r.returncode})", r.returncode == 0)
        c(f"{имя}: проверок не меньше {не_меньше} (прошло {прошли})", прошли >= не_меньше)
    return c.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
