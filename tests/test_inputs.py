"""Разбор того, что прислал клиент.

Восемьдесят с лишним раз по серверу стояло одно и то же: try/int/except. Само
по себе верное, но каждое такое место — шанс написать чуть иначе. И писали:
где-то забывали про запятую в дробных, где-то не ограничивали сверху, где-то
путали «не прислали» с «прислали ноль».

Теперь разбор один на всех, и проверять его надо здесь, а не в полусотне ручек.

Отдельно про None. «Не число» и «ноль» — разные вещи, и слить их нельзя:
нулевой потолок компенсаций ЗАПРЕЩАЕТ их совсем. Молча записать ноль вместо
непонятного ввода — значит выключить людям возможность и не сказать об этом.
"""
from _common import db, client, Checker, as_admin

from partut import inputs


def run():
    c = Checker("Целые числа")
    c("обычное", inputs.целое("5") == 5)
    c("с пробелами", inputs.целое("  7  ") == 7)
    c("мусор — не число", inputs.целое("не число") is None)
    c("пусто — не число", inputs.целое("") is None)
    c("None — не число", inputs.целое(None) is None)
    c("список — не число", inputs.целое([1, 2]) is None)
    c("умолчание отдаётся, когда не разобрали", inputs.целое("ерунда", 0) == 0)
    c("нижняя граница", inputs.целое("3", минимум=10) == 10)
    c("верхняя граница", inputs.целое("99", максимум=10) == 10)
    # True в Python — это 1, и int(True) молча вернул бы единицу. В поле числа
    # булево значит «клиент прислал не то», а не «прислал один».
    c("True числом не считается", inputs.целое(True) is None)
    c("дробь целым не считается", inputs.целое("3.7") is None)

    c2 = Checker("Дробные числа")
    c2("с точкой", inputs.дробное("12.5") == 12.5)
    # Телефон в русской раскладке даёт запятую, и половина покупателей пишет
    # цену именно так. Раньше на этом падал разбор — и человек видел
    # «проверьте поле» на совершенно правильном числе.
    c2("с запятой", inputs.дробное("12,5") == 12.5)
    c2("с пробелом внутри", inputs.дробное("1 000,5") == 1000.5)
    c2("мусор", inputs.дробное("почём?") is None)
    c2("умолчание", inputs.дробное("", 0.0) == 0.0)
    c2("границы", inputs.дробное("-5", минимум=0) == 0.0)
    # NaN и бесконечность арифметику не ломают, а тихо портят: NaN не равен
    # ничему, включая себя, и любая сумма с ним становится NaN навсегда.
    c2("NaN в деньгах — мусор", inputs.дробное("nan") is None)
    c2("бесконечность — тоже", inputs.дробное("inf") is None)
    c2("минус бесконечность — тоже", inputs.дробное("-inf") is None)

    c3 = Checker("Строки")
    c3("список строкой не считается", inputs._text([1, 2]) == "")
    c3("число превращается в строку", inputs._text(42) == "42")
    c3("обрезается по длине", inputs._text("длинная строка", 6) == "длинна")
    # Нулевой байт SQLite глотает молча, а Postgres отказывается принимать
    # такую строку вовсе — и запрос падает пятисоткой.
    c3("нулевой байт вычищается", "\x00" not in inputs._text("а\x00б"))

    # --- Границы работают на живых настройках ---
    c4 = Checker("Границы настроек магазина")
    as_admin()

    def сохранить(**поля):
        return client.post("/api/admin/settings/update",
                           json=dict({"initData": "x"}, **поля))

    сохранить(wheel_step=0)
    c4("нулевой шаг колеса не проходит (иначе прокрут за каждую покупку)",
       db.wheel_step() >= 1)
    сохранить(coins_per_byn=9999)
    c4("кэшбэк ограничен сверху", db.coins_per_byn() <= 10)
    сохранить(compensation_max=0)
    c4("а вот ноль компенсаций — законное значение", db.compensation_max() == 0)
    сохранить(compensation_max="не число")
    c4("мусор НЕ обнуляет настройку", db.compensation_max() == 0)
    сохранить(compensation_max=1000)
    c4("нормальное значение сохраняется", db.compensation_max() == 1000)
    сохранить(coins_per_byn="2,5")
    c4("запятая понята и здесь", abs(db.coins_per_byn() - 2.5) < 0.001)

    сохранить(coins_per_byn=1, wheel_step=100, compensation_max=1000)
    return c.fails + c2.fails + c3.fails + c4.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
