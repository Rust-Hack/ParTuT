"""Роль процесса: бот, сайт или оба сразу.

Бот и сайт живут одним процессом ради бесплатного тарифа: падение одного
роняет оба, а выкатка — это простой всего магазина. Разнести их правильно, но
на Render для второго процесса нужен платный Background Worker.

Поэтому режимы заведены заранее: когда до тарифа дойдут руки, разделение
станет правкой одной переменной, а не кода. Проверка следит, чтобы эта
возможность не сгнила незаметно — режимом, которым не пользуются, легко
сломать, ничего не заметив.

Отдельно — присмотр за ботом. infinity_polling переживает сетевые сбои сам, но
поток может умереть, и тогда магазин выглядит рабочим (сайт отвечает), а заказы
не доезжают до продавца. Узнать об этом было бы неоткуда, кроме жалоб.
"""
import importlib

from _common import Checker


def run():
    c = Checker("Роли процесса")
    run_mod = importlib.import_module("run")

    c("режимы объявлены", tuple(run_mod.РОЛИ) == ("all", "web", "bot"))
    c("присмотр за ботом есть", callable(getattr(run_mod, "_бот_под_присмотром", None)))

    # Главное свойство присмотра: упавший бот поднимается снова, а владелец
    # об этом узнаёт. Проверяем делом — подменяем сам опрос и сон.
    c2 = Checker("Упавший бот поднимается и о нём сообщают")
    попыток = {"n": 0}
    жалобы = []

    настоящий_бот = run_mod.bot.run
    import time as времямодуль
    настоящий_сон = времямодуль.sleep
    from partut import errors
    настоящая_жалоба = errors.report

    def падающий():
        попыток["n"] += 1
        if попыток["n"] >= 3:
            raise KeyboardInterrupt          # чем-то надо прервать вечный цикл
        raise RuntimeError("сеть отвалилась")

    run_mod.bot.run = падающий
    errors.report = lambda tg, где, беда, extra="": жалобы.append((где, str(беда)))
    времямодуль.sleep = lambda сек: None
    try:
        try:
            run_mod._бот_под_присмотром()
        except KeyboardInterrupt:
            pass
    finally:
        run_mod.bot.run = настоящий_бот
        errors.report = настоящая_жалоба
        времямодуль.sleep = настоящий_сон

    c2(f"после падения бот поднимался снова (попыток {попыток['n']})", попыток["n"] >= 2)
    c2(f"владельцу пожаловались ({len(жалобы)})", len(жалобы) >= 2)
    c2("в жалобе сказано, что это опрос Телеграма",
       all(ж[0] == "опрос Телеграма" for ж in жалобы))
    c2("и видно причину", any("сеть отвалилась" in ж[1] for ж in жалобы))

    return c.fails + c2.fails
