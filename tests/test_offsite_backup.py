"""Вторая копия базы — вне Телеграма.

Ежедневная копия уходила владельцу в Телеграм. То есть в тот же аккаунт,
которым он открывает магазин и в котором лежит токен бота: потеря доступа
отняла бы разом и управление, и все копии. Копия, лежащая в одной корзине с
оригиналом, — это не копия.

Здесь проверяется не «код вызывается», а три состояния, которые нельзя путать:
  • ушла — хорошо;
  • не ушла — беда, и о ней обязаны сказать;
  • не настроена — это НЕ успех, и выглядеть успехом не должно.

Сеть в прогоне не трогаем: хранилище подменяется.
"""
from _common import Checker

import bot as botmod
import offsite


def _подменить_телеграм():
    """Возвращает (список отправленного, вернуть-как-было)."""
    ушло = []
    настоящий = botmod.bot.send_document
    botmod.bot.send_document = lambda chat_id, doc, **kw: ушло.append((chat_id, doc, kw))
    return ушло, lambda: setattr(botmod.bot, "send_document", настоящий)


def run():
    c = Checker("Копия уходит в оба места")
    ушло, вернуть = _подменить_телеграм()
    сложено = []
    настоящая_отправка, настоящее_настроено = offsite.отправить, offsite.настроено
    offsite.отправить = lambda blob, имя: сложено.append((имя, len(blob))) or None
    offsite.настроено = lambda: True
    try:
        беда = botmod._send_backup([777])
        c("ошибки нет", беда is None)
        c("в Телеграм ушло", len(ушло) == 1)
        c("в хранилище тоже", len(сложено) == 1)
        c("в хранилище тот же файл", сложено[0][0].startswith("partut-")
          and сложено[0][0].endswith(".json.gz"))
        c("файл непустой", сложено[0][1] > 0)
        c("владельцу сказано, что вторая копия есть",
          "вторая копия в хранилище" in ушло[0][2].get("caption", ""))

        # --- Хранилище отказало ---
        c2 = Checker("Хранилище отказало — об этом говорят")
        ушло.clear(); сложено.clear()
        offsite.отправить = lambda blob, имя: "хранилище ответило 403: нет доступа"
        сообщено = []
        import errors
        настоящий_report = errors.report
        errors.report = lambda бот, где, e: сообщено.append(f"{где}: {e}")
        try:
            беда = botmod._send_backup([777])
        finally:
            errors.report = настоящий_report
        c2("копия в Телеграм всё равно ушла", len(ушло) == 1)
        c2("и это НЕ считается провалом целиком", беда is None)
        c2("но в подписи прямо сказано, что вторая не ушла",
           "вторая копия НЕ ушла" in ушло[0][2].get("caption", ""))
        c2("и разработчику сообщено", any("вторая копия" in s for s in сообщено))

        # --- Телеграм отказал, хранилище приняло ---
        c3 = Checker("Телеграм отказал — данные всё равно целы")
        offsite.отправить = lambda blob, имя: None
        botmod.bot.send_document = lambda *a, **k: (_ for _ in ()).throw(RuntimeError("нет сети"))
        беда = botmod._send_backup([777])
        c3("тревогу «копии нет» не поднимаем — она есть", беда is None)

        # А вот если отказали ОБА — это настоящая беда.
        offsite.отправить = lambda blob, имя: "и тут не вышло"
        errors.report = lambda *a, **k: None
        беда = botmod._send_backup([777])
        errors.report = настоящий_report
        c3("оба отказали — это провал", bool(беда))

        # --- Не настроено ---
        c4 = Checker("«Не настроено» не выдаётся за успех")
        ушло.clear()
        botmod.bot.send_document = lambda chat_id, doc, **kw: ушло.append((chat_id, doc, kw))
        offsite.настроено = lambda: False
        беда = botmod._send_backup([777])
        c("копия ушла", беда is None)
        подпись = ушло[-1][2].get("caption", "")
        c4("владелец видит, что второй копии нет", "не настроена" in подпись)
        c4("и почему это важно", "одном аккаунте" in подпись)
        c4("галочки об успехе при этом нет", "вторая копия в хранилище" not in подпись)
    finally:
        offsite.отправить, offsite.настроено = настоящая_отправка, настоящее_настроено
        вернуть()

    c5 = Checker("Кириллица в настройках не ломает отправку")
    # Обе беды поймала живая проверка на настоящем HTTP; на подменённом
    # хранилище их не видно вовсе, потому что requests в мок не заходит.
    #
    # 1. Папка «Копии магазина» — владелец заведёт её именно так, а без
    #    кодирования процентами requests падает ещё до сети.
    адрес = offsite._адрес_файла("http://х/копии магазина/", "partut-1.json.gz")
    c5("кириллица в пути закодирована", "%D0" in адрес and " " not in адрес)
    c5("имя файла на месте", адрес.endswith("partut-1.json.gz"))
    c5("схема и хост целы", адрес.startswith("http://"))

    # 2. Пароль по-русски — дело обычное, а requests кодирует его в latin-1
    #    и роняет отправку с UnicodeEncodeError.
    настоящие = offsite.USER, offsite.PASSWORD
    offsite.USER, offsite.PASSWORD = "вася", "секрет"
    try:
        заголовки = offsite._заголовки()
        c5("подпись собрана", заголовки.get("Authorization", "").startswith("Basic "))
        import base64 as _b64
        разобрано = _b64.b64decode(заголовки["Authorization"][6:]).decode("utf-8")
        c5("логин и пароль дошли как есть", разобрано == "вася:секрет")
    finally:
        offsite.USER, offsite.PASSWORD = настоящие

    c6 = Checker("Ненастроенное хранилище отвечает честно")
    настоящий_url = offsite.URL
    offsite.URL = ""
    try:
        c6("без адреса — внятный отказ, а не падение",
           "не настроено" in (offsite.отправить(b"x", "f.gz") or ""))
    finally:
        offsite.URL = настоящий_url

    return c.fails + c2.fails + c3.fails + c4.fails + c5.fails + c6.fails


if __name__ == "__main__":
    import sys
    sys.exit(1 if run() else 0)
