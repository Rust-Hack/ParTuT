"""export.py — выгрузка заказов в файл для Excel.

Лист: принимает уже прочитанные строки и отдаёт текст. Ни базы, ни Flask, ни
Telegram — поэтому формат можно проверить тестом, не поднимая магазин.

Одна строка файла — одна ПОЗИЦИЯ заказа, а не заказ целиком. Заказ из трёх
товаров даёт три строки с общим номером. Так с файлом можно работать сводной
таблицей: «сколько всего продали вот этого вкуса» — вопрос одного щелчка, а из
строки-заказа с товарами, слипшимися в одну ячейку, этого не достать никак.

Про формат чисел. Разделитель полей — точка с запятой, дробная часть — запятая,
в начале файла BOM. Это то сочетание, при котором русский Excel открывает файл
двойным щелчком и видит ЧИСЛА, а не текст. С точкой в дробной части он молча
считает «12.50» словом, суммы в таком столбце не складываются, и человек узнаёт
об этом, только когда итог окажется нулём.
"""

import csv
import io
import json

from partut import money

# Статусы словами. В приложении есть свой словарь (STATUS_RU в 04-admin.js), но
# там они во множественном числе для фильтров — «Выданы», а в строке файла
# уместно «Выдан». Разные слова для разной работы, а не забытая копия.
СТАТУСЫ = {
    "new": "Ждёт чек",
    "paid": "Ждёт подтверждения",
    "confirmed": "Подтверждён",
    "issued": "Выдан",
    "canceled": "Отклонён",
}

ОПЛАТА = {"cash": "Наличные", "card": "Карта"}

ЗАГОЛОВКИ = ["Дата", "Заказ", "Точка", "Статус", "Получение", "Оплата", "Покупатель",
             "Товар", "Вариант", "Кол-во", "Цена", "Сумма", "Скидка", "Выручка",
             "Закупка за шт", "Прибыль", "Промокод"]


def _ч(x):
    """Число для русского Excel: две цифры после запятой, запятая разделителем."""
    if x is None:
        return ""
    return f"{float(x):.2f}".replace(".", ",")


def строки_заказов(orders, coin_value, города=None):
    """Разворачивает заказы в плоские строки: по одной на позицию.

    У заказа с доставкой добавляется отдельная строка «Доставка». Без неё сумма
    столбца «Выручка» не сошлась бы с выручкой на экране: та считается по
    полю total, а доставка сидит именно в нём, но не в позициях.
    """
    города = города or {}
    out = []
    for o in orders:
        общее = [
            (o.get("created_at") or "")[:16],
            o.get("id"),
            города.get(o.get("city"), o.get("city") or ""),
            СТАТУСЫ.get(o.get("status"), o.get("status") or ""),
            o.get("delivery_method") or "Самовывоз",
            ОПЛАТА.get(o.get("payment_method"), o.get("payment_method") or ""),
            ("@" + o["username"]) if o.get("username") else str(o.get("user_id") or ""),
        ]
        # items в базе лежит строкой JSON. Битую строку пропускаем молча — но
        # только позиции: сам заказ в файле останется, с доставкой и статусом.
        # Уронить всю выгрузку из-за одного кривого заказа было бы хуже.
        try:
            сырое = o.get("items")
            товары = json.loads(сырое) if isinstance(сырое, str) else (сырое or [])
            позиции = money.разложить_заказ(товары, o.get("coins_used"),
                                            o.get("promo_discount"), coin_value)
        except (TypeError, ValueError):
            позиции = []
        for п in позиции:
            out.append(общее + [
                п["name"], п["flavor"], п["qty"],
                _ч(п["price"]), _ч(п["line"]), _ч(п["discount"]), _ч(п["revenue"]),
                _ч(п["cost"]) if п["cost"] else "",
                # Прочерк, а не ноль: закупочная цена не заполнена — значит
                # прибыль неизвестна, и складывать её с настоящей нельзя.
                _ч(п["profit"]) if п["profit"] is not None else "—",
                o.get("promo_code") or "",
            ])
        доставка = float(o.get("delivery_fee") or 0)
        if доставка:
            out.append(общее + ["Доставка", "", 1, _ч(доставка), _ч(доставка), _ч(0),
                                _ч(доставка), "", "—", o.get("promo_code") or ""])
    return out


def csv_заказов(orders, coin_value, города=None):
    """Готовый текст CSV со шляпкой. Кодировать в UTF-8 с BOM — дело отправителя."""
    буфер = io.StringIO()
    # \r\n — то, что Excel считает переводом строки во всех версиях.
    писарь = csv.writer(буфер, delimiter=";", quoting=csv.QUOTE_MINIMAL, lineterminator="\r\n")
    писарь.writerow(ЗАГОЛОВКИ)
    писарь.writerows(строки_заказов(orders, coin_value, города))
    return буфер.getvalue()


def в_файл(текст):
    """Текст → байты для Telegram. BOM обязателен: без него Excel читает файл в
    своей однобайтовой кодировке, и вместо названий товаров выходит каша."""
    return ("﻿" + текст).encode("utf-8")
