"""
tgsend.py — всё, что уходит наружу: сообщения людям и фоновые задачи.

Листовой по отношению к серверу: знает config и errors, но про приложение и
про ручки не знает ничего. Отправка нужна и веб-серверу, и боту, и пока она
жила в server.py, за одним send_message тянулось всё приложение целиком.

Здесь же живёт _bg — потому что почти всё, что уходит в фон, уходит именно в
Telegram, а Telegram отвечает через сеть. Ответ покупателю не должен ждать
чужого сервера: заказ к этому моменту уже в базе.
"""

import html
import os
import threading
import time
from concurrent.futures import ThreadPoolExecutor, wait

import telebot

from partut import errors
from partut.config import BOT_TOKEN, SUBSCRIBE_CHANNEL

# Отдельный экземпляр бота — ТОЛЬКО чтобы отправлять сообщения и картинки.
# Опрос обновлений ведёт partut/bot/handlers.py, здесь его нет и быть не должно.
tg = telebot.TeleBot(BOT_TOKEN)

try:
    BOT_USERNAME = tg.get_me().username
except Exception as e:
    print(f"Не смог узнать имя бота: {e}")
    BOT_USERNAME = ""


# Фоновые дела идут через ПУЛ, а не поток на каждое.
#
# Раньше каждый вызов bg() заводил новый поток. При обычной торговле это
# незаметно, а при всплеске — заказ, чек, уведомление продавцам, кэшбэк —
# потоки плодятся сотнями, и каждый висит на сети Telegram, который в этот
# момент как раз и тормозит. Память кончается на ровном месте, причём в
# единственный день, когда магазин работает в полную силу.
#
# Четырёх работников хватает: всё, что здесь делается, ждёт сеть, а не считает.
# Очередь при этом бесконечная и это правильно: отбросить уведомление о заказе
# нельзя — лучше оно придёт на секунду позже.
_ФОНОВЫХ_РАБОТНИКОВ = int(os.environ.get("BG_WORKERS", "4"))
_фон = ThreadPoolExecutor(max_workers=_ФОНОВЫХ_РАБОТНИКОВ, thread_name_prefix="фон")
_в_работе = set()
_учёт = threading.Lock()


def bg(fn, *args, **kwargs):
    """Запускает побочный эффект в фоне — чтобы ответ клиенту не ждал сети.

    Молчаливое падение здесь означало бы «заказ пришёл, но никто о нём не
    узнал» — худший сорт поломки, поэтому о сбое сообщаем владельцу.
    """
    def _run():
        # Импорт внутри функции намеренно: снаружи он развернул бы стрелку
        # tgsend → db, а этот модуль обязан оставаться листом.
        from partut import db
        try:
            fn(*args, **kwargs)
        except Exception as e:
            errors.report(tg, f"фоновая задача {getattr(fn, '__name__', fn)}", e)
        finally:
            # У фоновой задачи нет конца запроса, а значит нет и teardown'а:
            # соединение, брошенное здесь, не подберёт никто. А бросают их
            # именно здесь чаще всего — уведомления ходят в сеть и падают.
            забыто = db.вернуть_забытые()
            if забыто:
                print(f"[база] фон {getattr(fn, '__name__', fn)}: "
                      f"подобрано брошенных соединений: {забыто}", flush=True)
    дело = _фон.submit(_run)
    with _учёт:
        _в_работе.add(дело)
    дело.add_done_callback(lambda d: _в_работе.discard(d))
    return дело


def дождаться_фона(секунд=10):
    """Подождать, пока начатые фоновые дела доедут. True — доехали все.

    Магазину это не нужно: там ответ покупателю намеренно не ждёт Telegram.
    Нужно проверкам — иначе они читают список отправленного сразу после
    запроса и проверяют не магазин, а расторопность планировщика: на быстрой
    машине проходит, на загруженной нет.

    Ждём и те дела, что фон поставил сам, пока мы ждали; уже закончившееся,
    но ещё не вычеркнутое из учёта, ожиданием не считаем. Ответ «доехали ли»
    нужен проверке, которая после этого меряет что-то своё (приёмка QA-3C-01:
    хвост уведомлений прошлого заказа попадал в счёт подключений следующего).
    """
    срок = time.monotonic() + секунд
    while True:
        with _учёт:
            дела = {д for д in _в_работе if not д.done()}
        if not дела:
            return True
        осталось = срок - time.monotonic()
        if осталось <= 0:
            return False
        wait(дела, timeout=осталось)


def contact_link(username, uid, label=None):
    """HTML-ссылка «открыть чат в ТГ» по @username (t.me) или по id (tg://user).
    label — текст ссылки (по умолчанию @username или имя/id)."""
    username = (username or "").lstrip("@").strip()
    if username:
        url = f"https://t.me/{username}"
        text = label or f"@{username}"
    else:
        url = f"tg://user?id={uid}"
        text = label or str(uid)
    return f'<a href="{url}">{html.escape(text)}</a>'


def notify_client(user_id, text):
    """Сообщение клиенту (не роняем запрос, если он заблокировал бота)."""
    if not text:
        return
    try:
        tg.send_message(int(user_id), text)
    except Exception as e:
        print(f"Не смог уведомить клиента {user_id}: {e}")


_ПОДПИСАН = {"member", "administrator", "creator"}


def is_subscribed(user_id):
    """Подписан ли человек на обязательный канал. SUBSCRIBE_CHANNEL пуст —
    проверка выключена, все считаются подписанными.

    Сбой самого запроса (канал без бота-админа, сеть, опечатка в имени) не
    должен запереть весь магазин молча: возвращаем «подписан», но пишем в
    консоль — это ошибка настройки, а не покупателя, и владелец её увидит
    по логам, а не по толпе людей, которых не пускает в приложение."""
    if not SUBSCRIBE_CHANNEL:
        return True
    try:
        member = tg.get_chat_member(f"@{SUBSCRIBE_CHANNEL}", int(user_id))
        return member.status in _ПОДПИСАН
    except Exception as e:
        print(f"Не удалось проверить подписку {user_id} на @{SUBSCRIBE_CHANNEL}: {e}")
        return True


def notify_new_admin(uid, city):
    """Сообщаем человеку, что доступ выдан: иначе он не узнает, что теперь админ."""
    where = f" по точке «{city}»" if city else ""
    try:
        tg.send_message(uid, f"🛠 Вам выдали доступ продавца{where}.\n"
                             f"Откройте приложение — появится раздел «Управление».")
    except Exception as e:
        print(f"Не смог уведомить нового админа {uid}: {e}")
