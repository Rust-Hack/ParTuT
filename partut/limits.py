"""
limits.py — сколько раз подряд можно.

Листовой модуль: ничего своего не импортирует. Ограничивать частоту нужно и
ручкам заказа, и отзывам, и картинкам, и поддержке — а живи это в server.py,
за одной проверкой тянулось бы всё приложение.

Две разные меры, и путать их нельзя.

  • Пауза — «не чаще раза в N секунд, каждому своя». Про человека: он нажал
    дважды, потому что не понял, сработало ли.
  • Ведро — «не больше N раз в минуту на всех вместе». Про ресурс, который
    один на весь магазин и кончается: у нас это лимит обращений к Telegram.
    Токен у бота один, и через него же уходят заказы продавцам. Выжечь его
    картинками значит остановить торговлю, не тронув ни витрину, ни базу.

Обе меры живут в памяти процесса и при перезапуске забываются. Это осознанно:
общая на все процессы память означала бы поход в базу на каждый запрос, то
есть плату за защиту той самой скоростью, ради которой всё и делается.
"""

import threading
import time

# Работают ли паузы вообще.
#
# Нужно стенду. Проверка «оформил заказ, потом отменил, потом оформил снова»
# делает три запроса за миллисекунду — живой человек так не умеет, а антиспам
# не отличает одного от другого и справедливо отказывает. Гонять по проверкам
# искусственные задержки значит растянуть прогон на минуты ради того, чтобы
# всё осталось как было.
#
# Выключается ЯВНО и только стендом (tests/_common.py). Сами паузы при этом
# проверяются отдельно — tests/test_limits.py включает их обратно.
_РАБОТАЮТ = True


def выключить():
    """Стенд: считать, что пауза всегда истекла."""
    global _РАБОТАЮТ
    _РАБОТАЮТ = False


def включить():
    """Вернуть как в магазине."""
    global _РАБОТАЮТ
    _РАБОТАЮТ = True


class Пауза:
    """«Не чаще раза в N секунд» — отдельно для каждого ключа (обычно id).

    Словарь с потолком, и это не мелочь: ключи приходят снаружи, а словарь без
    края — утечка памяти с чужой рукой на кране. Раньше такой счётчик стоял в
    поддержке и рос ровно столько, сколько живёт процесс.
    """

    def __init__(self, секунд, максимум_ключей=5000):
        self.секунд = секунд
        self.максимум = максимум_ключей
        self._когда = {}
        self._замок = threading.Lock()

    def сколько_ждать(self, ключ):
        """0 — можно прямо сейчас (и мы это засчитали). Больше нуля — сколько
        секунд осталось до следующей попытки."""
        if not _РАБОТАЮТ:
            return 0
        сейчас = time.time()
        with self._замок:
            прошлое = self._когда.get(ключ, 0)
            осталось = self.секунд - (сейчас - прошлое)
            if осталось > 0:
                return осталось
            self._когда[ключ] = сейчас
            if len(self._когда) > self.максимум:
                self._подрезать(сейчас)
            return 0

    def _подрезать(self, сейчас):
        """Выкидываем всех, чья пауза давно вышла: они всё равно ничего не ждут."""
        протухли = [k for k, t in self._когда.items() if сейчас - t > self.секунд]
        for k in протухли:
            self._когда.pop(k, None)
        # Даже после уборки может быть тесно (все ключи свежие) — тогда режем
        # самых давних: они ближе всех к тому, чтобы стать ненужными.
        if len(self._когда) > self.максимум:
            по_старшинству = sorted(self._когда.items(), key=lambda kv: kv[1])
            for k, _ in по_старшинству[:len(self._когда) - self.максимум]:
                self._когда.pop(k, None)

    def забыть(self, ключ=None):
        """Сбросить паузу. Без ключа — всем (нужно тестам)."""
        with self._замок:
            self._когда.clear() if ключ is None else self._когда.pop(ключ, None)


class Ведро:
    """Токенное ведро: не больше «ёмкость» действий за «за_секунд», на всех вместе.

    Не «столько-то в секунду»: всплеск — это нормально. Магазин открыли, и
    двадцать картинок каталога полетели разом; отказывать здесь было бы хуже
    поломки. Ведро копит право на всплеск, пока им не пользуются, и упирается
    только в средний расход.
    """

    def __init__(self, ёмкость, за_секунд):
        self.ёмкость = float(ёмкость)
        self.скорость = float(ёмкость) / float(за_секунд)   # сколько восполняется в секунду
        self._есть = float(ёмкость)
        self._когда = time.monotonic()
        self._замок = threading.Lock()

    def взять(self, сколько=1):
        """True — разрешено (и списано). False — бюджет исчерпан."""
        сейчас = time.monotonic()
        with self._замок:
            self._есть = min(self.ёмкость,
                             self._есть + (сейчас - self._когда) * self.скорость)
            self._когда = сейчас
            if self._есть < сколько:
                return False
            self._есть -= сколько
            return True

    def наполнить(self):
        """Налить доверху (нужно тестам)."""
        with self._замок:
            self._есть = self.ёмкость
            self._когда = time.monotonic()
