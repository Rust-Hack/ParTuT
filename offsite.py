"""
offsite.py — вторая копия базы, вне Телеграма.

Зачем ещё одна, если копия и так уходит каждый день. Затем, что уходит она
владельцу в Телеграм — то есть в тот же аккаунт, которым он открывает магазин
и в котором лежит токен бота. Потеря доступа к аккаунту означала бы потерю
одновременно и управления, и всех копий. Резервная копия, лежащая в одной
корзине с оригиналом, — это не резервная копия.

Куда именно — решает владелец переменными окружения. Здесь намеренно нет
привязки к конкретному хранилищу: обычный HTTP PUT с логином и паролем
принимают и Яндекс.Диск, и Nextcloud, и любой WebDAV, и S3-совместимое
хранилище по временной ссылке.

    BACKUP_URL       https://webdav.yandex.ru/partut/   (папка, со слэшем)
    BACKUP_USER      логин
    BACKUP_PASSWORD  пароль приложения (НЕ основной пароль от аккаунта)

Не задано — молчим и говорим об этом честно: «не настроено» здесь не ошибка,
но и не успех, и путать эти два состояния нельзя.
"""

import base64
import os
from urllib.parse import quote, urlsplit, urlunsplit

import requests

URL = os.environ.get("BACKUP_URL", "").strip()
USER = os.environ.get("BACKUP_USER", "").strip()
PASSWORD = os.environ.get("BACKUP_PASSWORD", "").strip()

# Копия базы небольшая (десятки-сотни КБ), но сеть у хостинга бывает вялой.
ТАЙМАУТ = 60


def настроено():
    return bool(URL)


def _адрес_файла(база, имя):
    """Полный адрес файла, пригодный для отправки.

    Кириллица в пути обязана быть закодирована процентами. Это не мелочь:
    владелец естественным образом заведёт папку «Копии магазина», и без
    кодирования отправка падает на UnicodeEncodeError — то есть вторая копия
    не работала бы никогда, а узналось бы это в тот единственный день, когда
    она нужна. Поймано живой проверкой; на подменённом хранилище не видно.
    """
    части = urlsplit(база if база.endswith("/") else база + "/")
    путь = quote(части.path + имя, safe="/")
    return urlunsplit((части.scheme, части.netloc, путь, части.query, ""))


def _заголовки():
    """Заголовки запроса, включая логин с паролем.

    Собираем подпись сами, а не через auth=(...), по одной причине: requests
    кодирует её в latin-1, и пароль с кириллицей роняет отправку с
    UnicodeEncodeError ещё до всякой сети. Пароль по-русски — дело обычное,
    и вторая копия из-за этого не работала бы никогда. Браузеры давно шлют
    UTF-8; шлём и мы.
    """
    заголовки = {"Content-Type": "application/gzip"}
    if USER:
        пара = base64.b64encode(f"{USER}:{PASSWORD}".encode("utf-8")).decode("ascii")
        заголовки["Authorization"] = "Basic " + пара
    return заголовки


def отправить(blob, имя):
    """Кладёт копию в хранилище. Возвращает None при успехе или текст беды.

    Ошибку возвращаем, а не глотаем: копия, которая молча не уходит, хуже
    отсутствующей — на неё рассчитывают.
    """
    if not настроено():
        return "хранилище не настроено (BACKUP_URL)"
    адрес = _адрес_файла(URL, имя)
    try:
        ответ = requests.put(адрес, data=blob, timeout=ТАЙМАУТ, headers=_заголовки())
    except Exception as e:
        return f"{type(e).__name__}: {e}"
    # Успех у WebDAV — 201, у S3 и при перезаписи — 200 или 204.
    if ответ.status_code in (200, 201, 204):
        return None
    # Тело ответа обрезаем: у хранилищ там бывает километр XML, а в сообщении
    # владельцу нужна причина, а не дамп.
    хвост = (ответ.text or "").strip().replace("\n", " ")[:120]
    return f"хранилище ответило {ответ.status_code}: {хвост}"
